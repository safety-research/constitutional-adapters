#!/usr/bin/env python
"""full22: write the Petri SI-prefix VARIANT behavior dirs for a prompted baseline from the registry.

``configs/capeval/petri/<behavior>/<VARIANT>/BEHAVIOR.md`` exists for every SI in
``manifest.PETRI_PROMPTABLE_SI_IDS`` (the standup requires the dir for every prompted manifest
cell even in attacks mode; ``scenarios.behavior_files`` reads every variant on disk). The
variant carries the canonical behavior's frontmatter (``num_scenarios``, ``modality``) plus
``target_sysprompt_prefix`` = the EXACT registered SI text, and the canonical DESCRIPTION body
byte-for-byte — the tests pin ``front["target_sysprompt_prefix"] == BY_ID[<si>].text`` and
``body == canonical body`` for every behavior. Written by a script rather than by hand because
the full-constitution text is 182k characters: a hand copy is exactly the drift the H8 hash
exists to catch.

  python scripts/sdfbase/full22/write_prompted_variant_dirs.py --si constitution_full [--check]

The text goes in as a YAML literal block scalar with the clip indicator (``|``): the registered
text ends in exactly one newline, which ``|`` preserves, so the parsed value round-trips to the
registry bytes. A text that would not round-trip (a line that is a bare ``---``, a leading-space
first line, a text without a single trailing newline) is REFUSED, never quietly re-shaped.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO / "src"))
from sisteer.capeval import manifest as cm
from sisteer.capeval.petri import registry_adapter as ra
from sisteer.capeval.petri import scenarios as psc
from sisteer.data.instructions import BY_ID

PETRI_ROOT = REPO / "configs" / "capeval" / "petri"

NOTE = {
    "constitution_full": (
        "the FULL-CONSTITUTION prompted baseline (cell prompted__constitution_full; the\n"
        "# sdfbase-llama8b lane, 2026-09-10): the WHOLE constitution document as the system\n"
        "# prompt — data.instructions `si_constitution_full` = the vendored\n"
        "# src/sisteer/data/constitution_full.md, 39 sections / 28,977 words / 182,219 chars,\n"
        "# sha256 asserted at import (82f88c55...). Distinct from PROMPTED_CONSTITUTION, the\n"
        "# compressed EXCERPT (si_constitution). No Petri leg runs for this cell in the lane\n"
        "# (static families, best-of-N, MMLU, GSM8K only) — the dir exists because the\n"
        "# standup requires it for every prompted manifest cell (mt_serving_up.py), and its\n"
        "# bytes are what the H8 prefix hash (prompted_prefix_hashes.constitution_full) binds."),
}


def render(si: str, behavior: str) -> str:
    tt_id = ra.HARNESS_TO_TRAINTEST_SI[si]
    text = BY_ID[tt_id].text
    if not text.endswith("\n") or text.endswith("\n\n"):
        raise SystemExit(f"{tt_id}: the text must end in exactly one newline for the `|` scalar to round-trip")
    lines = text[:-1].split("\n")
    if lines[0][:1].isspace():
        raise SystemExit(f"{tt_id}: a leading-space first line needs an explicit indentation indicator; refusing")
    if any(l.strip() == "---" for l in lines):
        raise SystemExit(f"{tt_id}: a bare `---` line would terminate the frontmatter; refusing")
    canonical = (PETRI_ROOT / behavior / "BEHAVIOR.md").read_bytes()
    front, body = psc.parse_behavior_md(canonical)
    variant = cm.PETRI_SI_VARIANT_DIRS[si]
    head = (f"---\n# Petri Bloom SI-prefix variant (petri plan §6 H8): {NOTE[si]}\n"
            f"# This dir audits `{behavior}` under {variant}; it shares the ONE frozen canonical\n"
            f"# scenario bundle by content hash (petri-scenarios.lock.yaml) and holds NO scenario\n"
            f"# bytes of its own; scenarios/ is materialized read-only from the bundle at run time\n"
            f"# (M12). GENERATED by scripts/sdfbase/full22/write_prompted_variant_dirs.py from the\n"
            f"# registry — never hand-edited (the tests pin the prefix to BY_ID[{tt_id!r}].text).\n"
            f"num_scenarios: {front['num_scenarios']}\n"
            f"modality: {front['modality']}\n"
            f"target_sysprompt_prefix: |\n")
    scalar = "".join(("  " + l if l else "") + "\n" for l in lines)
    out = head + scalar + "---\n" + body + "\n"
    got_front, got_body = psc.parse_behavior_md(out.encode("utf-8"))
    if got_front["target_sysprompt_prefix"] != text or got_body != body:
        raise SystemExit(f"{variant}/{behavior}: the rendered file does not round-trip to the registry text")
    if (got_front["num_scenarios"], got_front["modality"]) != (front["num_scenarios"], front["modality"]):
        raise SystemExit(f"{variant}/{behavior}: frontmatter drift")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--si", required=True, choices=sorted(NOTE))
    ap.add_argument("--check", action="store_true", help="exit 1 if any committed variant drifts")
    args = ap.parse_args(argv)
    rc = 0
    for b in cm.PETRI_BEHAVIORS:
        dst = PETRI_ROOT / b / cm.PETRI_SI_VARIANT_DIRS[args.si] / "BEHAVIOR.md"
        text = render(args.si, b)
        if args.check:
            if not dst.is_file() or dst.read_text(encoding="utf-8") != text:
                print(f"DRIFT: {dst}"); rc = 1
            else:
                print(f"ok: {dst}")
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(text, encoding="utf-8"); print(f"wrote {dst}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
