#!/usr/bin/env python
"""A SCRATCH validation slice of one full22 (target, view): the bare anchor
plus a named subset of its cells, as a roster + config + manifest triple the
ordinary standup can consume unchanged.

Why this exists. Validating one cell should not require every OTHER cell of
the wave to be servable. The qwen35_4b `main` view currently cannot build at
all — its two `si12__safety_refusal__*` copies are staged with no
`train_budget_meta.json` (they carry `fit_provenance.json` / `summary.json`
instead), which the view builder has always refused and which is a STAGING
gap, nothing to do with the cells being sliced here. A slice lets a
serving change be validated against the real objects, on the real path, with
the real generated battery keys, while an unrelated staging gap is fixed by
whoever owns it.

Everything written is SCRATCH: it lands in --out, never in configs/, and it
is derived from the committed generated files by substituting exactly two
keys (`explicit_cells` in the config, `petri.cells` in the manifest) plus a
scratch `out_dir` / `private_run` / audit name. The cell -> staged-id map is
copied verbatim from the roster, so a slice can never serve an object the
roster does not map.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(HERE.parent))     # scripts/sdfbase, for the generator

import make_full22_configs as gen  # noqa: E402


def _sub_block(text: str, key: str, lines: list[str]) -> str:
    """Replace a top-level ``key:`` list block with ``lines``."""
    pat = re.compile(rf"^{re.escape(key)}:\n(?:- .*\n)+", re.M)
    if not pat.search(text):
        raise SystemExit(f"no top-level {key!r} list block to replace")
    return pat.sub(f"{key}:\n" + "".join(f"- {v}\n" for v in lines), text, count=1)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", required=True)
    ap.add_argument("--view", default="main", help="the SOURCE view to slice")
    ap.add_argument("--slice-view", default="validate",
                    help="the scratch view name (its own cells_view/<name> dir)")
    ap.add_argument("--cells", required=True,
                    help="comma-separated cell ids to keep (besides `none`)")
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args(argv)

    roster = gen.load_roster()
    t = roster["targets"][args.target]
    src_cells = gen.served_cells(roster, args.target, args.view)   # view cells + enabled lanes
    keep = [c.strip() for c in args.cells.split(",") if c.strip()]
    missing = [c for c in keep if c not in src_cells]
    if missing:
        raise SystemExit(
            f"{args.target}/{args.view} does not serve {missing} "
            f"(it serves {sorted(src_cells)}) — a slice never invents a cell")
    out = args.out
    out.mkdir(parents=True, exist_ok=True)

    # 1. the scratch roster the view builder reads (same staged-id mapping)
    slice_roster = {"wave": roster["wave"], "bank_root": roster["bank_root"],
                    "targets": {args.target: {"views": {args.slice_view: {
                        "cells": {c: src_cells[c] for c in keep}}}}}}
    roster_p = out / "slice_roster.yaml"
    roster_p.write_text(yaml.safe_dump(slice_roster, sort_keys=False))

    # 2. the config: the generated one with explicit_cells narrowed
    src_cfg = REPO / t["views"][args.view]["config"]
    cfg_text = _sub_block(src_cfg.read_text(encoding="utf-8"),
                          "explicit_cells", ["none"] + keep)
    tag = f"validate_{args.target}"
    cfg_text = re.sub(r"^defenses_dir: .*$",
                      f"defenses_dir: out/full22/{args.target}/cells_view/{args.slice_view}",
                      cfg_text, count=1, flags=re.M)
    cfg_text = re.sub(r"^out_dir: .*$", f"out_dir: out/scratch_{tag}",
                      cfg_text, count=1, flags=re.M)
    cfg_text = re.sub(r"^private_run: .*$", f"private_run: scratch_{tag}",
                      cfg_text, count=1, flags=re.M)
    cfg_p = out / "slice_config.yaml"
    cfg_p.write_text("# SCRATCH validation slice — generated by "
                     "make_validation_slice.py, never committed\n" + cfg_text)

    # 3. the manifest: the generated one with the same cells, as harness ids
    src_man = REPO / t["views"][args.view]["manifest"]
    man_text = src_man.read_text(encoding="utf-8")
    harness = ["none"] + [gen.harness_cell_id(c) for c in keep]
    pat = re.compile(r"^  cells:\n(?:    - .*\n)+", re.M)
    if not pat.search(man_text):
        raise SystemExit("no petri.cells block in the manifest")
    man_text = pat.sub("  cells:\n" + "".join(f"    - {c}\n" for c in harness),
                       man_text, count=1)
    man_text = re.sub(r"^  audit: .*$", f"  audit: scratch_{tag}", man_text,
                      count=1, flags=re.M)
    man_p = out / "slice_manifest.yaml"
    man_p.write_text("# SCRATCH validation slice — generated by "
                     "make_validation_slice.py, never committed\n" + man_text)

    # a slice must agree with itself the way the standup demands
    cfg = yaml.safe_load(cfg_p.read_text())
    man = yaml.safe_load(man_p.read_text())
    assert cfg["explicit_cells"] == ["none"] + keep, cfg["explicit_cells"]
    assert man["petri"]["cells"] == harness, man["petri"]["cells"]
    assert (man["petri"]["target_model"], man["petri"]["target_revision"]) == \
        (cfg["model"], cfg["model_revision"])

    print(json.dumps({"roster": str(roster_p), "config": str(cfg_p),
                      "manifest": str(man_p), "cells": cfg["explicit_cells"],
                      "harness_cells": harness,
                      "slice_view": args.slice_view,
                      "staged": {c: src_cells[c] for c in keep}}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
