#!/usr/bin/env python
"""The two PINNED 200-item subsets of bcb-bfcl-200: BigCodeBench (complete
split v0.1.2 minus the 148 Hard ids, seeded uniform draw) and BFCL (the
battery's 18 single-turn categories, Hamilton-stratified by size with a
floor of 1).

The RULES live in ``sisteer.capeval.tinycap.contracts`` (``bcb_select``,
``bfcl_select``, ``hash_order``, ``hamilton_allocation``) and are regenerated by
``tests/test_capeval_subsets.py``; this script only BUILDS the populations from
the pinned sources and writes the pin files:

    # network once (the two BigCodeBench parquets by revision through the HF
    # cache; gorilla @ dac44e7 through inspect_evals' own sparse clone)
    HF_HOME=/tmp/bcb-hf INSPECT_EVALS_CACHE_DIR=~/.cache/inspect_evals \\
        ~/venvs/tinycap-laneB/bin/python scripts/capeval_subsets.py --build

    # re-check that the pins on disk regenerate from their recorded populations
    python scripts/capeval_subsets.py --check

    # capeval-full-tasks (2026-09-23): the two FULL-population pins from the SAME
    # sources (bcb_full.json / bfcl_full.json; the 200 pins are NOT rewritten)
    HF_HOME=/tmp/bcb-hf INSPECT_EVALS_CACHE_DIR=~/.cache/inspect_evals \\
        ~/venvs/tinycap-laneB/bin/python scripts/capeval_subsets.py --build --full

Full-pin rule (``contracts.bcb_select_full`` / ``bfcl_select_full``): the whole
population, ``seed`` null, ``n == of``; BCB every complete-split id sorted by the
numeric suffix, Hard INCLUDED, with ``hard_ids`` listed BESIDE at the top level
for a stratified reading (``contracts.SUBSET_PIN_BCB_FULL_EXTRA_FIELDS``); BFCL
every id in category-name order (within a category the loader's recorded order)
with ``per_category`` = the population counts. The 200 pins' ids are subsets of
the full pins' (``tests/test_capeval_subsets.py`` asserts it).

Pin file shape (``contracts.SUBSET_PIN_FIELDS``): ``{schema, task,
generated_by, generated_at, dataset, source_sha256, seed, n, of, rule, ids,
population, per_category}``. BCB adds ``libs_by_id`` (the pinned items'
library lists, a Python-literal list string in the dataset) and ``per_family``
(the per-library-family counts through ``configs/capeval/tasks/
bcb_lib_families.json`` — a TOTAL, multi-label map; an unmapped lib is a
build/test failure); BFCL's ``population`` is ``{category_name: [ids]}`` — the
analysis join — and its ``per_category`` the Hamilton seats.
"""

from __future__ import annotations

import argparse
import ast
import datetime as _dt
import hashlib
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Mapping, Sequence

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from sisteer.capeval.tinycap import contracts as C  # noqa: E402

GENERATED_BY = "scripts/capeval_subsets.py"


# --------------------------------------------------------------------------- #
# pure helpers (imported by the tests)                                         #
# --------------------------------------------------------------------------- #


def canonical_json(doc: Mapping[str, Any]) -> str:
    return json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


#: The TOTAL ``lib -> family`` map and the multi-label per-family counts: the
#: contracts' verified readers, which ``load_bcb_pin`` holds the written pin to
#: as well — one definition, so the builder cannot drift from the loader.
load_lib_families = C.bcb_lib_families
per_family_counts = C.bcb_per_family_counts


def parse_libs(value: Any) -> List[str]:
    """The dataset's ``libs`` column is a Python-literal list string."""
    if isinstance(value, str):
        parsed = ast.literal_eval(value)
    else:
        parsed = list(value)
    return [str(x) for x in parsed]


def build_bcb_pin(*, ids: Sequence[str], hard_ids: Sequence[str], libs_by_task: Mapping[str, Sequence[str]],
                  families: Mapping[str, str], source_sha256: Mapping[str, str],
                  generated_at: str) -> Dict[str, Any]:
    """The BCB pin document from its population (pure; the test rebuilds it)."""
    picked = C.bcb_select(ids, hard_ids, n=C.BCB_SUBSET_N, seed=C.SUBSET_SEED)
    libs_by_id = {i: list(libs_by_task[i]) for i in picked}
    return {
        "schema": C.SUBSET_PIN_SCHEMA,
        "task": "bigcodebench_200",
        "generated_by": GENERATED_BY,
        "generated_at": generated_at,
        "dataset": {"complete": {"repo_id": C.BCB_DATASET, "revision": C.BCB_DATASET_REVISION,
                                 "split": C.BCB_SPLIT, "n": len(ids)},
                    "hard": {"repo_id": C.BCB_HARD_DATASET, "revision": C.BCB_HARD_DATASET_REVISION,
                             "split": C.BCB_SPLIT, "n": len(hard_ids)}},
        "source_sha256": dict(source_sha256),
        "seed": C.SUBSET_SEED,
        "n": C.BCB_SUBSET_N,
        "of": len(ids) - len(hard_ids),
        "rule": (f"population = the {C.BCB_SPLIT} complete split's task_ids ({len(ids)}) minus the "
                 f"BigCodeBench-Hard task_ids ({len(hard_ids)}) = {len(ids) - len(hard_ids)}; order the "
                 f"population by sha256(f'{{seed}}:{{task_id}}') with seed {C.SUBSET_SEED} "
                 f"(contracts.hash_order) and take the first {C.BCB_SUBSET_N}; report sorted by the "
                 "numeric id suffix (contracts.bcb_select)"),
        "ids": picked,
        "population": {"ids": [str(i) for i in ids], "hard_ids": sorted({str(i) for i in hard_ids},
                                                                       key=lambda i: int(C.bcb_log_id(i)))},
        "per_category": {},
        "libs_by_id": libs_by_id,
        "per_family": per_family_counts(libs_by_id, families),
    }


def build_bcb_full_pin(*, ids: Sequence[str], hard_ids: Sequence[str], libs_by_task: Mapping[str, Sequence[str]],
                       families: Mapping[str, str], source_sha256: Mapping[str, str],
                       generated_at: str) -> Dict[str, Any]:
    """The BigCodeBench FULL pin document from its population (pure; the test
    rebuilds it): every complete-split id, Hard included, ``seed`` null."""
    picked = C.bcb_select_full(ids, hard_ids)
    hard_sorted = sorted({str(i) for i in hard_ids}, key=lambda i: int(C.bcb_log_id(i)))
    libs_by_id = {i: list(libs_by_task[i]) for i in picked}
    return {
        "schema": C.SUBSET_PIN_SCHEMA,
        "task": C.CONTROL_BIGCODEBENCH_FULL,
        "generated_by": GENERATED_BY,
        "generated_at": generated_at,
        "dataset": {"complete": {"repo_id": C.BCB_DATASET, "revision": C.BCB_DATASET_REVISION,
                                 "split": C.BCB_SPLIT, "n": len(ids)},
                    "hard": {"repo_id": C.BCB_HARD_DATASET, "revision": C.BCB_HARD_DATASET_REVISION,
                             "split": C.BCB_SPLIT, "n": len(hard_ids)}},
        "source_sha256": dict(source_sha256),
        "seed": C.FULL_PIN_SEED,
        "n": len(picked),
        "of": len(ids),
        "rule": (f"population = the {C.BCB_SPLIT} complete split's task_ids ({len(ids)}), the BigCodeBench-Hard "
                 f"task_ids ({len(hard_ids)}) INCLUDED; take the whole population, no seed; report sorted by the "
                 "numeric id suffix (contracts.bcb_select_full), with the Hard ids listed beside under hard_ids "
                 "for a stratified Hard / non-Hard reading"),
        "ids": picked,
        "population": {"ids": [str(i) for i in ids], "hard_ids": hard_sorted},
        "per_category": {},
        "libs_by_id": libs_by_id,
        "per_family": per_family_counts(libs_by_id, families),
        "hard_ids": hard_sorted,
    }


def build_bfcl_full_pin(*, population: Mapping[str, Sequence[str]], source_sha256: Mapping[str, str],
                        generated_at: str) -> Dict[str, Any]:
    """The BFCL FULL pin document from its ``{category_name: [ids]}`` population
    (pure): every id in category-name order, ``per_category`` = the counts."""
    ids, counts = C.bfcl_select_full(population)
    of = sum(len(v) for v in population.values())
    return {
        "schema": C.SUBSET_PIN_SCHEMA,
        "task": C.CONTROL_BFCL_FULL,
        "generated_by": GENERATED_BY,
        "generated_at": generated_at,
        "dataset": {"repo": "ShishirPatil/gorilla", "commit": C.BFCL_GORILLA_COMMIT_FULL,
                    "loader": f"inspect_evals-{C.INSPECT_EVALS_PIN} bfcl(categories=bfcl_categories())",
                    "categories": sorted(population), "n": of},
        "source_sha256": dict(source_sha256),
        "seed": C.FULL_PIN_SEED,
        "n": len(ids),
        "of": of,
        "rule": (f"population = inspect_evals' bfcl() over the battery's bfcl_categories() (V1 u V2 minus "
                 f"rest; {len(population)} categories, {of} items) grouped by metadata.category_name; take the "
                 "whole population, no seed; report in category-name order, within a category in the loader's "
                 "recorded order; per_category = the population counts (contracts.bfcl_select_full)"),
        "ids": ids,
        "population": {c: [str(i) for i in population[c]] for c in sorted(population)},
        "per_category": counts,
    }


def build_bfcl_pin(*, population: Mapping[str, Sequence[str]], source_sha256: Mapping[str, str],
                   generated_at: str) -> Dict[str, Any]:
    """The BFCL pin document from its ``{category_name: [ids]}`` population."""
    ids, seats = C.bfcl_select(population, n=C.BFCL_SUBSET_N, seed=C.SUBSET_SEED)
    of = sum(len(v) for v in population.values())
    return {
        "schema": C.SUBSET_PIN_SCHEMA,
        "task": "bfcl_200",
        "generated_by": GENERATED_BY,
        "generated_at": generated_at,
        "dataset": {"repo": "ShishirPatil/gorilla", "commit": C.BFCL_GORILLA_COMMIT_FULL,
                    "loader": f"inspect_evals-{C.INSPECT_EVALS_PIN} bfcl(categories=bfcl_categories())",
                    "categories": sorted(population), "n": of},
        "source_sha256": dict(source_sha256),
        "seed": C.SUBSET_SEED,
        "n": C.BFCL_SUBSET_N,
        "of": of,
        "rule": (f"population = inspect_evals' bfcl() over the battery's bfcl_categories() (V1 u V2 minus "
                 f"rest; {len(population)} categories, {of} items) grouped by metadata.category_name; "
                 f"seats per category by the largest-remainder (Hamilton) rule with a floor of 1 — "
                 f"q_c = {C.BFCL_SUBSET_N} * n_c / N, a_c = max(1, floor(q_c)), the remaining seats one "
                 "each to the categories ordered by (remainder q_c - floor(q_c) DESCENDING, category_name "
                 "ASCENDING) (contracts.hamilton_allocation); within a category order the ids by "
                 f"sha256(f'{{seed}}:{{id}}') with seed {C.SUBSET_SEED} and take the first a_c "
                 "(contracts.hash_order); report in category-name order (contracts.bfcl_select)"),
        "ids": ids,
        "population": {c: [str(i) for i in population[c]] for c in sorted(population)},
        "per_category": seats,
    }


# --------------------------------------------------------------------------- #
# population builds (network / cache reads)                                    #
# --------------------------------------------------------------------------- #


def bcb_population() -> Dict[str, Any]:
    """The two parquets by revision through the HF cache (``HF_HOME``):
    ``(ids, hard_ids, libs_by_task, source_sha256)``."""
    import pyarrow.parquet as pq
    from huggingface_hub import hf_hub_download

    def fetch(repo_id: str, revision: str) -> Path:
        return Path(hf_hub_download(repo_id, f"data/{C.BCB_SPLIT}-00000-of-00001.parquet",
                                    repo_type="dataset", revision=revision))

    full = fetch(C.BCB_DATASET, C.BCB_DATASET_REVISION)
    hard = fetch(C.BCB_HARD_DATASET, C.BCB_HARD_DATASET_REVISION)
    tf, th = pq.read_table(full, columns=["task_id", "libs"]), pq.read_table(hard, columns=["task_id"])
    ids = [str(x) for x in tf.column("task_id").to_pylist()]
    libs = [parse_libs(x) for x in tf.column("libs").to_pylist()]
    hard_ids = [str(x) for x in th.column("task_id").to_pylist()]
    if len(ids) != C.BCB_FULL_N or len(hard_ids) != C.BCB_HARD_N:
        raise SystemExit(f"BigCodeBench: {len(ids)} complete / {len(hard_ids)} hard rows != the contracts' "
                         f"{C.BCB_FULL_N} / {C.BCB_HARD_N}")
    if any(ids[i] != f"BigCodeBench/{i}" for i in range(len(ids))):
        raise SystemExit("BigCodeBench: task_ids are not contiguous BigCodeBench/0..N-1 — the thin task's "
                         "position == id assumption would not hold")
    return {"ids": ids, "hard_ids": hard_ids, "libs_by_task": dict(zip(ids, libs)),
            "source_sha256": {"complete_parquet": hashlib.sha256(full.read_bytes()).hexdigest(),
                              "hard_parquet": hashlib.sha256(hard.read_bytes()).hexdigest()}}


def bfcl_population() -> Dict[str, Any]:
    """``{category_name: [ids]}`` through inspect_evals' own loader over the
    battery's categories (``INSPECT_EVALS_CACHE_DIR`` names the cache; the
    loader sparse-clones gorilla at its pinned commit when absent)."""
    from inspect_evals.bfcl.bfcl import BFCL_GITHUB_COMMIT, bfcl
    from sisteer.capeval.tiers import inspect_served as I

    if BFCL_GITHUB_COMMIT != C.BFCL_GORILLA_COMMIT_FULL:
        raise SystemExit(f"inspect_evals pins gorilla {BFCL_GITHUB_COMMIT}, the contracts "
                         f"{C.BFCL_GORILLA_COMMIT_FULL} — re-pin deliberately")
    cats = I.bfcl_categories()
    task = bfcl(categories=cats)
    pop: Dict[str, List[str]] = {c: [] for c in cats}
    for s in task.dataset:
        pop[str(s.metadata["category_name"])].append(str(s.id))
    if sum(len(v) for v in pop.values()) != C.BFCL_FULL_N:
        raise SystemExit(f"BFCL: {sum(len(v) for v in pop.values())} items != the contracts' {C.BFCL_FULL_N}")
    digest = hashlib.sha256(json.dumps({c: sorted(v) for c, v in pop.items()}, sort_keys=True).encode()).hexdigest()
    return {"population": pop, "source_sha256": {"population_by_category": digest,
                                                 "gorilla_commit": C.BFCL_GORILLA_COMMIT_FULL}}


def write_pins(repo_root: Path = REPO) -> None:
    now = _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat()
    families = load_lib_families(repo_root)
    b = bcb_population()
    bcb = build_bcb_pin(ids=b["ids"], hard_ids=b["hard_ids"], libs_by_task=b["libs_by_task"],
                        families=families, source_sha256=b["source_sha256"], generated_at=now)
    f = bfcl_population()
    bfcl = build_bfcl_pin(population=f["population"], source_sha256=f["source_sha256"], generated_at=now)
    for rel, doc in ((C.BCB_PIN_PATH, bcb), (C.BFCL_PIN_PATH, bfcl)):
        p = repo_root / rel
        p.write_text(canonical_json(doc), encoding="utf-8")
        print(f"[subsets] wrote {rel}: n={doc['n']} of={doc['of']} sha256={sha256_text(canonical_json(doc))[:12]}")
    # the pins must load through the contracts' verified loaders
    C.load_bcb_pin(repo_root)
    C.load_bfcl_pin(repo_root)
    print(f"[subsets] BCB per_family: {bcb['per_family']}")
    print(f"[subsets] BFCL per_category: {bfcl['per_category']}")


def write_full_pins(repo_root: Path = REPO) -> None:
    """capeval-full-tasks: the two FULL pins from the SAME population builds;
    the 200 pins on disk are NOT touched (their generated_at stays)."""
    now = _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat()
    families = load_lib_families(repo_root)
    b = bcb_population()
    bcb = build_bcb_full_pin(ids=b["ids"], hard_ids=b["hard_ids"], libs_by_task=b["libs_by_task"],
                             families=families, source_sha256=b["source_sha256"], generated_at=now)
    f = bfcl_population()
    bfcl = build_bfcl_full_pin(population=f["population"], source_sha256=f["source_sha256"], generated_at=now)
    for rel, doc in ((C.BCB_FULL_PIN_PATH, bcb), (C.BFCL_FULL_PIN_PATH, bfcl)):
        p = repo_root / rel
        p.write_text(canonical_json(doc), encoding="utf-8")
        print(f"[subsets] wrote {rel}: n={doc['n']} of={doc['of']} sha256={sha256_text(canonical_json(doc))[:12]}")
    C.load_bcb_full_pin(repo_root)
    C.load_bfcl_full_pin(repo_root)
    # the 200 pins' ids are subsets of the full pins' — by construction, checked here too
    for rel_small, rel_full in ((C.BCB_PIN_PATH, C.BCB_FULL_PIN_PATH), (C.BFCL_PIN_PATH, C.BFCL_FULL_PIN_PATH)):
        small = json.loads((repo_root / rel_small).read_text())
        full = json.loads((repo_root / rel_full).read_text())
        if not set(small["ids"]) <= set(full["ids"]):
            raise SystemExit(f"{rel_small}: pinned ids are not a subset of {rel_full}")
        if small["source_sha256"] != full["source_sha256"]:
            raise SystemExit(f"{rel_small}: source_sha256 {small['source_sha256']} != {rel_full}'s "
                             f"{full['source_sha256']} — the two pins were not built from the same sources")
    print(f"[subsets] BCB full per_family: {bcb['per_family']}")
    print(f"[subsets] BFCL full per_category: {bfcl['per_category']}")


def check_pins(repo_root: Path = REPO) -> int:
    ok = True
    for name, loader in (("bcb", C.load_bcb_pin), ("bfcl", C.load_bfcl_pin),
                         ("bcb_full", C.load_bcb_full_pin), ("bfcl_full", C.load_bfcl_full_pin)):
        try:
            doc = loader(repo_root)
            print(f"[subsets] {name}: ok — n={doc['n']} of={doc['of']} seed={doc['seed']}")
        except C.SubsetPinError as e:
            ok = False
            print(f"[subsets] {name}: REFUSED — {e}")
    families = load_lib_families(repo_root)
    for rel in (C.BCB_PIN_PATH, C.BCB_FULL_PIN_PATH):
        if not (repo_root / rel).is_file():
            continue
        bcb = json.loads((repo_root / rel).read_text())
        got = per_family_counts(bcb["libs_by_id"], families)
        if got != bcb["per_family"]:
            ok = False
            print(f"[subsets] {rel} per_family drift: {got} != {bcb['per_family']}")
    return 0 if ok else 2


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--build", action="store_true", help="build the populations (network once) and write both pins")
    ap.add_argument("--full", action="store_true",
                    help="with --build: write the two FULL-population pins (bcb_full.json / bfcl_full.json) instead "
                         "of the 200 pins (capeval-full-tasks); the 200 pins on disk are left untouched")
    ap.add_argument("--check", action="store_true", help="verify the pins on disk regenerate from their rules")
    ap.add_argument("--repo-root", default=str(REPO))
    a = ap.parse_args(argv)
    root = Path(a.repo_root)
    if a.full and not a.build:
        raise SystemExit("--full is a --build mode: pass --build --full")
    if a.build:
        (write_full_pins if a.full else write_pins)(root)
    if a.check or not a.build:
        return check_pins(root)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
