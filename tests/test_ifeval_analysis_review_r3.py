# --------------------------------------------------------------------------- S1: no-log mode cannot pass production
def test_no_log_mode_leaves_i4_and_i5_pending_and_no_flag_waives_it(llama_report):
    rep = llama_report
    v, g = rep["verdict"], rep["gates"]
    assert g["I4_scoring_path"]["status"] == g["I5_at_cap"]["status"] == A.GATE_PENDING
    assert g["I4_scoring_path"]["eval_logs_read"] is False and g["I5_at_cap"]["texts_reclassified"] is False
    assert g["I4_scoring_path"]["detail"] == A.EVAL_LOGS_PENDING_I4 and g["I5_at_cap"]["detail"] == A.EVAL_LOGS_PENDING_I5
    assert all("never waivable" in g[k]["detail"] for k in A.LOG_DERIVED_GATES)
    assert v["production"] is False and v["eval_logs_validated"] is False and v["comparison_only"] is False
    assert v["gates_pending_log_derived"] == ["I4_scoring_path", "I5_at_cap"] == list(A.LOG_DERIVED_GATES)
    assert g["pending_unwaivable"] == ["I4_scoring_path", "I5_at_cap"] and g["pending"] == ["I4_scoring_path", "I5_at_cap", "I9_report_match"]
    refusals = A.production_refusals(rep)
    assert len(refusals) == 2 and all("PENDING (never waivable)" in r for r in refusals)
    assert A.refusals_beyond_eval_logs(rep) == [] and A.non_log_gates_clear(rep)
    # `--allow-pending-gates` waives another unwaivable PENDING (a population gate) and NEVER a log-derived one
    waived = copy.deepcopy(rep)
    waived["allow_pending_gates"] = True
    waived["gates"]["I7_population"] = A._gate(A.GATE_PENDING, "no canonical ids file", waivable=False)
    A.refresh_gate_aggregates(waived["gates"])
    waived["verdict"] = A.verdict_of(waived)
    assert waived["verdict"]["production"] is False and waived["verdict"]["gates_pending_log_derived"] == list(A.LOG_DERIVED_GATES)
    wr = A.production_refusals(waived)
    assert not any("I7_population" in r for r in wr) and all(f"gate {k} PENDING (never waivable)" in " ".join(wr) for k in A.LOG_DERIVED_GATES)
    # and the same report with the logs "read" would be production: the verdict is a pure function of the gates — where "read"
    # means the PASS carries its evidence flag (`eval_logs_read` / `texts_reclassified` True); a bare PASSED without the
    # flag is the shape report-only certification used to accept, and is refused (`tests/test_ifeval_certification_evidence.py`)
    read = copy.deepcopy(rep)
    for k in A.LOG_DERIVED_GATES:
        read["gates"][k] = A._gate(A.GATE_PASS, None, **{A.LOG_DERIVED_EVIDENCE[k]: True})
    A.refresh_gate_aggregates(read["gates"])
    assert A.verdict_of(read)["production"] is True and A.verdict_of(read)["eval_logs_validated"] is True
    bare = copy.deepcopy(rep)
    for k in A.LOG_DERIVED_GATES:
        bare["gates"][k] = A._gate(A.GATE_PASS, None)
    A.refresh_gate_aggregates(bare["gates"])
    assert A.verdict_of(bare)["production"] is False and A.verdict_of(bare)["gates_passed_without_evidence"] == list(A.LOG_DERIVED_GATES)


def test_a_corrupted_partition_is_not_certified_by_a_no_log_pass(tmp_path):
    """The revision-2 test asserted I5 PASSED here (`read_eval_logs=False` after a consistent loop -> eligible move) — the bypass in
    test form. Now the internally consistent record is PENDING, never PASSED, and the report is not production; with the logs the
    r2 module's test still refuses the move by name."""
    m = _rows(NONE_G)
    G.build_store(tmp_path, row(*NONE_G), at_cap={(i, 0) for i in range(5)}, loops={(0, 0), (1, 0)})
    rec_path = tmp_path / IC.ifeval_paths(*NONE_G, 2048).cap_ladder
    rec = json.loads(rec_path.read_text())
    _consistent_move(rec, (G.IDS[0], 0))
    rec_path.write_text(json.dumps(rec))
    rep = analyze(tmp_path, m, read_eval_logs=False)
    leg = rep["legs"][V.leg_key(*NONE_G, 2048)]
    assert leg["ladder_problem"] is None                                     # internally consistent: the identity half passes
    assert rep["gates"]["I5_at_cap"]["status"] == A.GATE_PENDING and rep["gates"]["I5_at_cap"]["texts_reclassified"] is False
    assert rep["gates"]["I5_at_cap"]["legs"][V.leg_key(*NONE_G, 2048)] == A.GATE_PASS            # the per-leg identity map is kept
    assert rep["verdict"]["production"] is False and "I5_at_cap" in rep["verdict"]["gates_pending_log_derived"]
    assert any("I5_at_cap PENDING (never waivable)" in r for r in A.production_refusals(rep))
    # a per-leg FAILURE of the identity half still FAILS (PENDING never masks a failure)
    rec["n_loop"] += 1
    rec_path.write_text(json.dumps(rec))
    rep2 = analyze(tmp_path, m, read_eval_logs=False)
    assert rep2["gates"]["I5_at_cap"]["status"] == A.GATE_FAIL and rep2["verdict"]["production"] is False


def test_a_comparison_only_report_claims_nothing_and_publishes_nothing(llama_report, tmp_path):
    rep = copy.deepcopy(llama_report)
    rep["comparison_only"] = {"mode": A.COMPARISON_ONLY_MODE, "eval_logs_read": False}
    rep["verdict"] = A.verdict_of(rep)
    assert rep["verdict"]["comparison_only"] is True and rep["verdict"]["production"] is False
    assert any(r.startswith(f"a {A.COMPARISON_ONLY_MODE} report") for r in A.production_refusals(rep)) and A.refusals_beyond_eval_logs(rep) == []
    with pytest.raises(A.AnalysisError, match="comparison-only"):
        A.make_figures(rep, tmp_path / "figs")
    assert not (tmp_path / "figs").exists()
    with pytest.raises(A.AnalysisError, match="comparison-only"):
        A.render_results_md(rep)
    with pytest.raises(A.AnalysisError, match="comparison-only"):
        A.log_wandb(rep, {}, mode="disabled")                                  # refused before the mode is even read
    # the mode block is outside the two-venv comparison; the comparison-only report compares equal to the production-shaped one
    assert "comparison_only" not in A.comparable_report(rep) and A.report_match(llama_report, rep)["equal"]
    # the command-line contract, as a pure function of the parsed arguments
    ap = A.build_parser()
    base = ["--gen-root", "x", "--sha", G.SHA7]
    assert "only with --compare-only" in A.comparison_only_argument_problem(ap.parse_args([*base, "--no-eval-logs"]))
    assert "requires --require-report-match" in A.comparison_only_argument_problem(ap.parse_args([*base, "--compare-only"]))
    for extra in (["--results-md", "r.md"], ["--figs-dir", "f"], ["--wandb-name", "w"], ["--wandb-name-suffix", "s"], ["--wandb-mode", "offline"]):
        problem = A.comparison_only_argument_problem(ap.parse_args([*base, "--compare-only", "--require-report-match", "ref.json", *extra]))
        assert problem and "publishes nothing" in problem, extra
    assert A.comparison_only_argument_problem(ap.parse_args([*base, "--compare-only", "--require-report-match", "ref.json", "--no-eval-logs"])) is None
    assert A.comparison_only_argument_problem(ap.parse_args([*base, "--require-report-match", "ref.json"])) is None      # a production pass held to a report


