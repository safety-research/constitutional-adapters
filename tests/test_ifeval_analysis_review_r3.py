def test_the_served_object_reading_is_generated_by_fit_condition_from_the_exit_and_loop_fields(llama_report):
    rep = llama_report
    k_it, k_main = V.cell_key(LLAMA, "it", LORA), V.cell_key(LLAMA, "main", LORA)
    fr_it, fr_main = rep["final_readouts"][k_it], rep["final_readouts"][k_main]
