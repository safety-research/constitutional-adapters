"""The compiled tinycap client lock (``configs/capeval/tinycap-client-
requirements.txt``).


The Modal image installs the client venv from this file with ``uv pip install
--no-deps --require-hashes`` and FAILS the build on non-resolution — no version
fallback, no unpinned install. So the lock itself must hold: it exists; it was
compiled from the ``.in`` with ``--generate-hashes`` under the recorded
``--exclude-newer`` cut-off; every non-VCS requirement carries at least one
``--hash=sha256:``; the top-level pins equal the ``.in`` (inspect_ai 0.3.260 +
inspect_evals 0.18.0 co-resolved — the spec's open question); the one VCS
requirement is the commit-pinned IFEval checker (the only line uv cannot
hash, installed separately at that exact commit); and the resolved
transitive set carries no floating specifier. CPU-only, no installs.
"""

from __future__ import annotations

import re
from pathlib import Path

from sisteer.capeval.tinycap import contracts as C

REPO = Path(__file__).resolve().parents[1]
LOCK = REPO / C.CLIENT_LOCK_TXT
LOCK_IN = REPO / C.CLIENT_LOCK_IN

_REQ = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]+\])?==([^ \\]+)")


def _blocks() -> list[list[str]]:
    """The lock as requirement blocks: a requirement line plus its
    continuation (`--hash`) and `# via` comment lines."""
    blocks, cur = [], []
    for line in LOCK.read_text().splitlines():
        if not line.strip():
            continue
        if line.startswith("#"):
            continue                      # the header
        if line.startswith((" ", "\t")):
            cur.append(line)
            continue
        if cur:
            blocks.append(cur)
        cur = [line]
    if cur:
        blocks.append(cur)
    return blocks


def _pins() -> dict[str, str]:
    out = {}
    for b in _blocks():
        m = _REQ.match(b[0])
        if m:
            out[m.group(1).lower().replace("_", "-")] = m.group(3)
    return out


def test_lock_exists_and_records_its_compile_command():
    assert LOCK.is_file(), f"{C.CLIENT_LOCK_TXT} missing — compile it from {C.CLIENT_LOCK_IN}"
    head = "\n".join(LOCK.read_text().splitlines()[:3])
    assert "autogenerated by uv" in head
    assert "uv pip compile" in head and C.CLIENT_LOCK_IN in head
    assert "--generate-hashes" in head
    assert f"--exclude-newer {C.CLIENT_LOCK_EXCLUDE_NEWER}" in head
    assert f"--python-version {C.CLIENT_PYTHON}" in head
    assert f"-o {C.CLIENT_LOCK_TXT}" in head, "the header must name the in-repo output path"
    # compiled with the repo's own [tool.uv] settings kept out, so the recorded cut-off is the only one applied
    assert "--no-config" in head and "--no-config" in LOCK_IN.read_text()


def test_every_non_vcs_requirement_is_hashed_and_exact():
    blocks = _blocks()
    assert len(blocks) > 100                       # inspect_ai alone pulls ~150
    vcs = [b for b in blocks if " @ " in b[0]]
    pinned = [b for b in blocks if " @ " not in b[0]]
    # the VCS allow-list: EXACTLY the contracts' one commit-pinned line, the josejg
    # IFEval checker at a full 40-hex commit; the installers split out exactly it
    assert sorted(b[0] for b in vcs) == sorted(C.CLIENT_VCS_PINS), [b[0] for b in vcs]
    assert len(C.CLIENT_VCS_PINS) == 1
    assert f"instruction-following-eval @ git+{C.IFEVAL_CHECKER_GIT}@{C.IFEVAL_CHECKER_REV}" in C.CLIENT_VCS_PINS
    for line in C.CLIENT_VCS_PINS:
        assert re.fullmatch(r"[a-z-]+ @ git\+https://github\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+@[0-9a-f]{40}", line), line
    for b in pinned:
        head = b[0]
        assert _REQ.match(head), f"not an exact pin: {head!r}"
        assert head.rstrip().endswith("\\"), f"pin without a hash continuation: {head!r}"
        hashes = [l for l in b[1:] if l.strip().startswith("--hash=sha256:")]
        assert hashes, f"{head!r} carries no --hash"
        for h in hashes:
            assert re.fullmatch(r"\s+--hash=sha256:[0-9a-f]{64}( \\)?", h), h
    # no floating specifier anywhere (>=, ~=, <, > or a bare name)
    for b in blocks:
        assert not re.search(r"(>=|~=|<=|<|>)", b[0].split(" #")[0]), b[0]


def test_top_level_pins_equal_the_in_and_the_spec():
    pins = _pins()
    for name, ver in C.CLIENT_TOP_LEVEL_PINS.items():
        key = name.lower().replace("_", "-")
        assert pins.get(key) == ver, (name, ver, pins.get(key))
    # the spec's open question: inspect_ai 0.3.260 + inspect_evals 0.18.0 co-resolve
    assert pins["inspect-ai"] == C.INSPECT_AI_PIN == "0.3.260"
    assert pins["inspect-evals"] == C.INSPECT_EVALS_PIN == "0.18.0"
    assert pins["evalplus"] == C.EVALPLUS_PIN
    # the .in's top-level set is exactly what the lock was compiled from
    in_lines = [l.strip() for l in LOCK_IN.read_text().splitlines()
                if l.strip() and not l.strip().startswith("#")]
    in_names = {(_REQ.match(l).group(1) if _REQ.match(l) else l.split(" @ ")[0])
                .lower().replace("_", "-") for l in in_lines}
    vcs_names = {line.split(" @ ")[0] for line in C.CLIENT_VCS_PINS}
    assert in_names <= set(pins) | vcs_names
    for name in vcs_names:
        assert name not in pins, name             # a VCS line is not an == pin


def test_lock_carries_the_ifeval_checker_dependencies():
    """inspect_evals' ``ifeval`` extra is in the ``.in`` (it brings langdetect);
    the josejg checker rides as the VCS line at the full sha inspect_evals
    0.18.0's own lock names, installed ``--no-deps``, so every runtime
    dependency its pyproject declares (immutabledict, langdetect, nltk, pandas,
    typer) and the ``rich`` it imports must be hashed lines here; immutabledict
    is a top-level pin. absl-py is only the checker's dev extra."""
    pins = _pins()
    text = LOCK_IN.read_text()
    assert "inspect_evals[math,bfcl,ifeval]==0.18.0" in text
    assert f"instruction_following_eval @ git+{C.IFEVAL_CHECKER_GIT}@{C.IFEVAL_CHECKER_REV}" in text
    assert pins["immutabledict"] == C.CLIENT_TOP_LEVEL_PINS["immutabledict"] == "4.3.1"
    assert pins["langdetect"] == "1.0.9"
    assert pins["nltk"] == "3.10.3"
    for dep in ("immutabledict", "langdetect", "nltk", "pandas", "typer", "rich"):
        assert dep in pins, dep
    assert C.IFEVAL_CHECKER_REV.startswith("0c495b2") and len(C.IFEVAL_CHECKER_REV) == 40


def test_lock_carries_the_client_side_facts_the_plan_relies_on():
    pins = _pins()
    # Inspect's openai-v3 / pydantic>=2.13 ceilings are exactly why the client
    # venv is SEPARATE from the vLLM venv: confirm they are here
    assert pins["openai"].split(".")[0] >= "3"
    assert tuple(int(x) for x in pins["pydantic"].split(".")[:2]) >= (2, 13)
    # torch (CPU use only: the driver imports sisteer.models) and scipy are top-level
    # pins now; the removed tier-1 harness that first pulled them in is gone
    assert pins["torch"] == C.CLIENT_TOP_LEVEL_PINS["torch"] and pins["scipy"] == C.CLIENT_TOP_LEVEL_PINS["scipy"]
    for gone in ("lm-eval", "tinybenchmarks", "peft", "accelerate", "rouge-score", "sacrebleu"):
        assert gone not in pins, gone
    assert pins["aiohttp"] == "3.14.3"            # the ledger runs in this venv


def test_lock_carries_the_agentic_sandbox_deps():
    """inspect-sandboxes 0.5.0 and swebench 5.0.2 are in THIS lock (they resolve
    under the cutoff with zero existing pins moved); inspect-sandboxes is the
    base of the bcb-bfcl-200 owned-sandbox provider (``tiers/sandbox_owned.py``),
    so the lock carries the Modal SDK it needs (>= 1.5.0) and swebench's docker
    driver, with no litellm (whose ``openai<3`` ceiling would move the openai
    3.x the test above asserts)."""
    pins = _pins()
    assert pins["inspect-sandboxes"] == C.CLIENT_TOP_LEVEL_PINS["inspect-sandboxes"] == "0.5.0"
    assert pins["swebench"] == C.CLIENT_TOP_LEVEL_PINS["swebench"] == "5.0.2"
    assert tuple(int(x) for x in pins["modal"].split(".")[:2]) >= (1, 5)     # inspect-sandboxes' floor
    assert "docker" in pins                                                  # swebench's sandbox driver
    assert "litellm" not in pins
    assert pins["openai"].split(".")[0] >= "3"
    text = LOCK_IN.read_text()
    assert "inspect-sandboxes==0.5.0" in text and "swebench==5.0.2" in text
