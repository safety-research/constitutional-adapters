GRADE_SITE = "SISTEER_CLUSTERS=cluster_a\nSISTEER_PRIMARY_CLUSTER=cluster_a\nSISTEER_GRADE_DIR=/srv/grade-runs\n"
GRADE_RULE = "regex\t(?<![/~\\w$-])grade-runs/\t$GRADE/\tconfigs/*\n"


def _grade_release(tmp_path, prose: str = None):
    """A recorded JSON file whose relative provenance path a rename table turns into a ``$GRADE`` path."""
    pre = json.dumps({"entry": {"source": "grade-runs/ladder/a.json", "n": 3}}, indent=1) + "\n"
    private, inputs = {"rename.tsv": GRADE_RULE}, [{"role": "rename", "file": "rename.tsv"}]
    if prose is not None:
        private["prose.tsv"] = prose
        inputs.append({"role": "prose", "file": "prose.tsv"})
    return _plain_release(tmp_path, {"configs/admission.json": pre},
                          {"configs/admission.json": pre.replace("grade-runs/", "$GRADE/")}, private, inputs,
                          config_env=GRADE_SITE)


