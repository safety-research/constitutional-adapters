def test_a_placeholder_that_expands_elsewhere_refuses(tmp_path):
    # the bytes are exactly the declared rules applied, but on this site $SHARED is another directory
    rel = Release(tmp_path, site_root="/data/site/bob")
    rc, out = rel.run()
    assert rc == 1, out
    assert "the committed bytes are not" not in out, "the byte re-derivation itself passes"
