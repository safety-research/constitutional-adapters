"""``scripts/release/scrub_map.py`` on synthetic pre and post trees: a rule-only change is certified, and every edit the
rules do not produce refuses.

Each test builds a throwaway git repository with a pre-release commit and a post-release commit, private inputs (rename
and placeholder tables, a line table, a header table and their manifest) in a separate directory, and a site config
whose cluster root the placeholder expands to. The site module is a small stand-in with the interface of
``sisteer.site`` (``NAMES``, ``PLACEHOLDERS``, ``load_site``, ``expand``), so the test needs nothing outside this
directory; the last test runs the same tree through the real module when the checkout has it.

The planted defects: an edited numeric parameter, an off-table comment edit, a placeholder that expands to another
path on the site, an embedded sha the release forgot to move, a historical sha it moved, a hand-edited map, a map
written under other inputs, an input whose bytes no longer match the manifest, a rule declared as plain text that
changes a value, a checkout-prefix removal that does not leave a relative path, a rename that turns a relative path
into a placeholder path, a host label renamed with no alias for it, and a rename that changes a number or the parsed
shape.
"""
from __future__ import annotations

import hashlib
import importlib
import importlib.util
import io
import json
import subprocess
import sys
import types
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("_scrub_map_tool", REPO / "scripts/release/scrub_map.py")
sm = importlib.util.module_from_spec(_spec)
sys.modules["_scrub_map_tool"] = sm
_spec.loader.exec_module(sm)


# --- a stand-in for sisteer.site ---------------------------------------------------------------------------------------

def _stub_site_module() -> types.ModuleType:
    mod = types.ModuleType("stub_site")
    mod.PLACEHOLDERS = {
        "SHARED": (("SISTEER_SHARED_ROOT", "CLUSTER_SHARED_ROOT"), (), "CLUSTER_SHARED_ROOT"),
        "HF_HOME": (("HF_HOME", "SISTEER_HF_HOME"), (), "CLUSTER_HF_HOME"),
        "STATE": (("SISTEER_STATE_ROOT",), ("SISTEER_STATE_ROOT",), None),
        "STAGE": (("SISTEER_STAGE_DIR",), ("SISTEER_STAGE_DIR",), None),
        "GRADE": (("SISTEER_GRADE_DIR",), ("SISTEER_GRADE_DIR",), None),
        "WANDB_PROJECT": (("WANDB_PROJECT", "SISTEER_WANDB_PROJECT"), ("SISTEER_WANDB_PROJECT",), None),
    }
    mod.NAMES = tuple(mod.PLACEHOLDERS)

    def parse(path):
        out = {}
        for line in Path(path).read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                out[k.strip()] = v.strip().strip("'\"")
        return out

    class Site:
        def __init__(self, path, config, clusters):
            self.path, self.config, self.clusters = path, config, clusters

        @property
        def labels(self):
            return list(self.clusters)

    def load_site(path, *, env=None):
        config = parse(path)
        clusters = {lab: parse(Path(path).parent / "clusters" / f"{lab}.env")
                    for lab in config.get("SISTEER_CLUSTERS", "").split()}
        return Site(str(path), config, clusters)

    def expand(value, cluster=None, *, site=None, env=None, key=None):
        name = value.strip("${}")
        envs, keys, ckey = mod.PLACEHOLDERS[name]
        for var in envs:
            if (env or {}).get(var):
                return env[var]
        for k in keys:
            if site.config.get(k):
                return site.config[k]
        label = cluster or site.config.get("SISTEER_PRIMARY_CLUSTER")
        block = site.clusters.get(label or "", {})
        if ckey and block.get(ckey):
            return block[ckey]
        raise ValueError(f"${name} is not set on this site (cluster {label!r})")

    mod.load_site, mod.expand = load_site, expand
    return mod


# --- the synthetic release ---------------------------------------------------------------------------------------------

ROOT_A = "/data/site/alice"          # the literal the placeholder replaces
PRE_WAVE = f"""# wave config
# tuned on oldsite_a (see note Q12)
model: tiny
temperature: 0.7
harmful_prompts_path: {ROOT_A}/prompts/harmful.json
runs_on: oldsite_a
store_dir: {ROOT_A}/stores
"""
POST_WAVE = """# wave config
# tuned on the first cluster
model: tiny
temperature: 0.7
harmful_prompts_path: $SHARED/prompts/harmful.json
runs_on: cluster_a
store_dir: $SHARED/stores
"""
HEADER_OLD = "# generated by gen.py from the wave config (note Q7)"
HEADER_NEW = "# generated by gen.py from the wave config"


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def _sampled(header: str, wave_sha: str, served_sha: str, body: str) -> str:
    return (f"{header}\n"
            f"source_config_sha256: {wave_sha}\n"
            f"serving_config_sha256: {served_sha}\n"
            f"{body}")


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@example.invalid",
                           "-c", "core.hooksPath=/dev/null", "-c", "commit.gpgsign=false", "-c", "gc.auto=0",
                           "-c", "maintenance.auto=false", *args],
                          check=True, capture_output=True, text=True).stdout.strip()


def _commit(repo: Path, files: dict, message: str) -> str:
    for rel, text in files.items():
        p = repo / rel
        if text is None:
            p.unlink()
            continue
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", message)
    return _git(repo, "rev-parse", "HEAD")


def _pre_files() -> dict:
    wave_body_pre = "temperature: 0.7\n" + f"cache: {ROOT_A}/cache\n"
    sampled = _sampled(HEADER_OLD, _sha(PRE_WAVE), _sha(PRE_WAVE), wave_body_pre)
    return {
        "configs/wave.yaml": PRE_WAVE,
        "configs/wave_sampled.yaml": sampled,
        "configs/unrecorded.yaml": f"path: {ROOT_A}/other\n",
        "configs/history.json": json.dumps({"serving_config_sha256": _sha(PRE_WAVE)}, indent=1) + "\n",
        "src/note.txt": "unrelated\n",
    }


def _post_files(*, wave: str = POST_WAVE, sampled_wave_sha: str = None, served_sha: str = None,
                header: str = HEADER_NEW) -> dict:
    """The post-release tree as the rules produce it (written out by hand, not by the tool), with optional defects."""
    pre = _pre_files()
    body_post = "temperature: 0.7\ncache: $SHARED/cache\n"
    sampled = _sampled(header, sampled_wave_sha or _sha(wave), served_sha or _sha(PRE_WAVE), body_post)
    return {
        "configs/wave.yaml": wave,
        "configs/wave_sampled.yaml": sampled,
        "configs/unrecorded.yaml": "path: $SHARED/other\n",
        "configs/history.json": pre["configs/history.json"],
        "src/note.txt": "unrelated, edited\n",
    }


def _default_private() -> dict:
    return {
        "rename.tsv": "# identifier renames\nword\toldsite_a\tcluster_a\n",
        "placeholder.tsv": f"literal\t{ROOT_A}\t$SHARED\n",
        "lines.jsonl": json.dumps({"path": "configs/wave.yaml", "old": "# tuned on oldsite_a (see note Q12)",
                                   "new": "# tuned on the first cluster"}) + "\n",
        "header.jsonl": json.dumps({"old": HEADER_OLD, "new": HEADER_NEW}) + "\n",
    }


DEFAULT_INPUTS = [{"role": "line_table", "file": "lines.jsonl"}, {"role": "header", "file": "header.jsonl"},
                  {"role": "placeholder", "file": "placeholder.tsv"}, {"role": "rename", "file": "rename.tsv"}]


class Release:
    """A pre-release commit, a post-release commit, private inputs and a site. The defaults are one rule-only release;
    each argument replaces one part of it."""

    def __init__(self, tmp: Path, *, post: dict = None, site_root: str = ROOT_A, rename_extra: str = "",
                 pre: dict = None, private: dict = None, inputs: list = None, recorded: list = None,
                 config_env: str = None):
        self.tmp = tmp
        self.repo = tmp / "repo"
        self.repo.mkdir(parents=True)
        _git(self.repo, "init", "-q")
        pre_files = pre if pre is not None else _pre_files()
        self.pre = _commit(self.repo, pre_files, "pre")
        self.post = _commit(self.repo, post if post is not None else _post_files(), "post")
        priv = tmp / "private"
        priv.mkdir()
        files = private if private is not None else _default_private()
        if rename_extra:
            files = dict(files, **{"rename.tsv": files["rename.tsv"] + rename_extra})
        for name, text in files.items():
            (priv / name).write_text(text)
        self.inputs = inputs if inputs is not None else DEFAULT_INPUTS
        self.recorded = priv / "recorded.txt"
        if recorded is None:
            p = _pre_files()
            recorded = [(_sha(p["configs/wave.yaml"]), "run config"),
                        (_sha(p["configs/wave_sampled.yaml"])[:16], "grading config prefix")]
        self.recorded.write_text("".join(f"{s}\t{label}\n" for s, label in recorded))
        self.manifest = priv / "manifest.json"
        self.write_manifest()
        site = tmp / "site"
        (site / "clusters").mkdir(parents=True)
        (site / "config.env").write_text(config_env if config_env is not None
                                         else "SISTEER_CLUSTERS=cluster_a\nSISTEER_PRIMARY_CLUSTER=cluster_a\n")
        (site / "clusters" / "cluster_a.env").write_text(f"CLUSTER_SHARED_ROOT={site_root}\n")
        self.site = site
        self.map = tmp / "SCRUB_MAP.tsv"

    def write_manifest(self, **extra) -> None:
        priv = self.manifest.parent
        entries = []
        for spec in self.inputs:
            ent = {k: v for k, v in spec.items() if k != "file"}
            if "file" in spec:
                ent["path"] = spec["file"]
                ent["sha256"] = hashlib.sha256((priv / spec["file"]).read_bytes()).hexdigest()
            entries.append(ent)
        man = {"format": "scrub-map-inputs/1", "pre_ref": self.pre, "inputs": entries}
        man.update(extra)
        self.manifest.write_text(json.dumps(man, indent=1))

    def run(self, *extra: str, verify: bool = False, site_module=None):
        out = io.StringIO()
        argv = ["--pre-ref", self.pre, "--inputs", str(self.manifest), "--site", str(self.site),
                "--repo", str(self.repo), "--post-ref", self.post, "--no-registry", "--no-frame",
                "--recorded", str(self.recorded)]
        argv += ["--verify", "--map", str(self.map)] if verify else ["--out", str(self.map)]
        rc = sm.run(argv + list(extra), site_module=site_module or _stub_site_module(), out=out)
        return rc, out.getvalue()


def _rows(map_path: Path):
    lines = [ln for ln in map_path.read_text().splitlines() if ln and not ln.startswith("#")]
    assert tuple(lines[0].split("\t")) == sm.COLUMNS
    return [dict(zip(sm.COLUMNS, ln.split("\t"), strict=True)) for ln in lines[1:]]


# --- a rule-only change ------------------------------------------------------------------------------------------------

def test_a_rule_only_change_is_mapped_and_certified(tmp_path):
    rel = Release(tmp_path)
    rc, out = rel.run()
    assert rc == 0, out
    rows = {r["path"]: r for r in _rows(rel.map)}
    # recorded by full sha, recorded by a sha prefix; the unrecorded change, the unchanged history file and the
    # file outside any record get no row
    assert set(rows) == {"configs/wave.yaml", "configs/wave_sampled.yaml"}, out
    pre, post = _pre_files(), _post_files()
    for path, r in rows.items():
        assert r["pre_sha256"] == _sha(pre[path]) and r["post_sha256"] == _sha(post[path])
        assert r["pre_path"] == path and r["kind"] == "config"
    text = rel.map.read_text()
    rule_set = next(ln.split()[2] for ln in text.splitlines() if ln.startswith("# rule_set "))
    inputs_line = next(ln[len("# inputs "):] for ln in text.splitlines() if ln.startswith("# inputs "))
    assert hashlib.sha256(inputs_line.encode()).hexdigest() == rule_set
    assert {r["rule_set"] for r in rows.values()} == {rule_set}
    # the committed header names no private path: the inputs are reduced to role, format and sha256
    assert str(rel.manifest.parent) not in text and "rename.tsv" not in text
    assert "substitutions: 3 resolved on the site" in out
    rc, out = rel.run(verify=True)
    assert rc == 0, out
    assert "CERTIFIED: 2 of 2 rows" in out


def test_the_map_is_readable_by_the_runtime_reader(tmp_path):
    rel = Release(tmp_path)
    rc, out = rel.run()
    assert rc == 0, out
    reader_path = REPO / "src/sisteer/scrub_map.py"
    if not reader_path.is_file():
        pytest.skip("the runtime reader sisteer.scrub_map is not in this checkout")
    reader = importlib.import_module("sisteer.scrub_map")
    m = reader.parse(rel.map.read_text(), str(rel.map))
    assert len(m) == 2
    pre, post = _pre_files(), _post_files()
    p = "configs/wave.yaml"
    assert reader.check(_sha(pre[p]), _sha(post[p]), path=p, map_path=rel.map) == reader.VIA_MAP


