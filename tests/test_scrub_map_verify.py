def test_a_historical_key_holds_only_where_its_globs_say(tmp_path):
    # source_sha256 records data in the capeval task files, and is a generated pin (which moves) everywhere else
    rel = Release(tmp_path)
    rel.write_manifest(historical_keys=[{"key": "roster_sha256", "paths": ["configs/frozen/*"]}])
    inputs = _load(rel)
    pre, post = "a" * 64, "b" * 64
    subst, prefixes = sm.substitution_tables([sm.Change("x", "x", pre, post, b"", b"")])
    text = f'{{"source_sha256": "{pre}", "roster_sha256": "{pre}"}}\n'.encode()
    moved = sm.derive(text, "configs/sdfbase/ifeval/matrix.json", inputs, subst, prefixes).post_text()
    assert moved == f'{{"source_sha256": "{post}", "roster_sha256": "{post}"}}\n'
    kept = sm.derive(text, "configs/capeval/tasks/bcb_200.json", inputs, subst, prefixes).post_text()
    assert kept == f'{{"source_sha256": "{pre}", "roster_sha256": "{post}"}}\n'
    frozen = sm.derive(text, "configs/frozen/roster.json", inputs, subst, prefixes).post_text()
    assert frozen == f'{{"source_sha256": "{post}", "roster_sha256": "{pre}"}}\n'


