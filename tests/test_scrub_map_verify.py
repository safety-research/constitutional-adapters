# --- a committed tool as a rename --------------------------------------------------------------------------------------

FAKE_RENAMER = '''
class _Table:
    def __init__(self, pairs):
        self.pairs = pairs

    def rewrite_text(self, text, path):
        for old, new in self.pairs:
            text = text.replace(old, new)
        return text

    def rewrite_path(self, path):
        return self.rewrite_text(path, path)


def load_rules(path):
    pairs = []
    for line in open(path, encoding="utf-8"):
        if line.strip() and not line.startswith("#"):
            old, new = line.rstrip("\\n").split("\\t")
            pairs.append((old, new))
    return _Table(pairs)
'''


def test_a_committed_loader_method_renames_text_and_paths(tmp_path):
    pre_cfg = "runs_on: oldsite_a\nkeep: 1\n"
    post_cfg = "runs_on: cluster_a\nkeep: 1\n"
    rel = Release(tmp_path,
                  pre={"configs/oldsite_a_wave.yaml": pre_cfg, "scripts/release/renamer.py": FAKE_RENAMER},
                  post={"configs/oldsite_a_wave.yaml": None, "configs/cluster_a_wave.yaml": post_cfg},
                  private={"renames.tsv": "oldsite_a\tcluster_a\n"},
                  inputs=[{"role": "rename", "apply": "scripts/release/renamer.py:load_rules.rewrite_text",
                           "file": "renames.tsv"}],
                  recorded=[(_sha(pre_cfg), "run config")])
    rc, out = rel.run()
    assert rc == 0, out
    (row,) = _rows(rel.map)
    assert (row["pre_path"], row["path"]) == ("configs/oldsite_a_wave.yaml", "configs/cluster_a_wave.yaml")
    # the commitment names the committed tool by its source sha256, never the private table's path
    text = rel.map.read_text()
    assert hashlib.sha256(FAKE_RENAMER.encode()).hexdigest() in text and "renames.tsv" not in text


