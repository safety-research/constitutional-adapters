def test_a_placeholder_rule_that_is_not_faithful_refuses(tmp_path):
    # a table that maps the root to the wrong placeholder: the bytes follow the table, the values do not survive
    wave = POST_WAVE.replace("$SHARED", "$STATE")
    post = {k: v.replace("$SHARED", "$STATE") for k, v in _post_files(wave=wave).items()}
    private = dict(_default_private(), **{"placeholder.tsv": f"literal\t{ROOT_A}\t$STATE\n"})
    rel = Release(tmp_path, post=post, private=private,
                  config_env="SISTEER_CLUSTERS=cluster_a\nSISTEER_STATE_ROOT=/var/state\n")
    rc, out = rel.run()
    assert rc == 1, out
    assert "the committed bytes are not" not in out, "the bytes follow the table"
    assert "'$STATE' does not expand to the '/data/site/alice' it replaced" in out


