def test_pick_refuses_an_over_threshold_confirmation_an_unmeasured_one_and_requests_for_an_unconfirmed_lr(tmp_path, capsys):
    cfg = _cfg_conf(tmp_path)
    _p, refit, _r9 = _confirmed_world(tmp_path, cfg)
    ap = str(tmp_path / "allowed_pairs.json")
    # the confirmation ran but clipped on 40 % of its steps: the regime FD 6 forbids is never promoted — refused by name
    _metrics(tmp_path / "r9_t00", over=4)
    with pytest.raises(SystemExit, match=r"rank 16 / set mlp at lr .*\(refit:fitted_argmin\) is not promotable — "
                                         r"clip activation 40.0% at r9_t00 is at/over the 25% promotion limit.*pick again"):
        hpo_pick.main(["--search-dir", str(tmp_path), "--rank", "16", "--set", "mlp", "--allowed-pairs", ap,
                       "--model-key", "toy_moe"])
    assert not (tmp_path / "hpo_pick.json").exists()               # dry run: the refusal writes nothing
    assert "DRY-RUN: registry ruling add" in capsys.readouterr().out   # the pick itself is recorded either way
    # a confirmation without a measurement is not evidence of the regime either: refused (a trial ran, unmeasured)
    (tmp_path / "r9_t00" / "metrics.jsonl").unlink()
    src = hpo_pick.lr_for_pair(hpo_pick.load_search(tmp_path, ap), (16, "mlp"))
    assert src["clip_evidence"]["verdict"] == "refused" and "no clip-activation measurement" in src["clip_evidence"]["reason"]
