def test_a_changed_pick_while_the_first_confirm_trial_is_queued_reserves_a_new_immutable_identity(tmp_path, monkeypatch, capsys):
    """Pick A requests its confirm trial (t00); the trial is QUEUED on the cluster, so the mirror holds no r8_t00 yet.
    The user changes their pick: the new request must NOT reuse index 0 (before the fix `len(glob("r8_t*"))` gave 0
    again, both jobs read one r8_trials.json and wrote one r8_t00) — it reserves index 1 with its own design path and
    job name, names the pending request it supersedes, and t00's file is byte-for-byte untouched. Each design emitted
    from its immutable request carries its own row index, so run_trial (and the sbatch) write different directories."""
    cfg = _cfg_conf(tmp_path)
    _confirmed_world(tmp_path, cfg)                                    # the winner (16, mlp) is confirmed
    ap = str(tmp_path / "allowed_pairs.json")
    monkeypatch.setattr(hpo_pick, "_run_registry", lambda argv, execute: None)

    def argv(rank, set_id):
        return ["--search-dir", str(tmp_path), "--rank", str(rank), "--set", set_id, "--allowed-pairs", ap,
                "--model-key", "toy_moe", "--fit-key", "toy_moe_base", "--execute"]

    req_p = tmp_path / hpo_pick.CONFIRM_PICK_REQUEST_NAME
    t00_p = tmp_path / hpo_pick.confirm_pick_request_name(0)
    t01_p = tmp_path / hpo_pick.confirm_pick_request_name(1)
    # 1. pick A (16, down): index 0 reserved, the ledger entry and the pointer agree, no predecessor
    assert hpo_pick.main(argv(16, "down")) == 0
    out = capsys.readouterr().out
    assert "reserved index 0: trial r8_t00, design r8_t00_trials.json, job suffix r8-t00" in out
    a = json.loads(req_p.read_text())
    assert a == json.loads(t00_p.read_text()) and a["predecessor"] is None
    assert a["index"] == 0 and a["trial_id"] == "r8_t00" and a["design"] == "r8_t00_trials.json"
    assert a["job_suffix"] == "r8-t00" and a["request"] == t00_p.name and a["pair"] == [16, "down"]
    assert hpo_pick.confirm_pick_identity(0) == {"index": 0, "trial_id": "r8_t00", "design": "r8_t00_trials.json", "job_suffix": "r8-t00"}
    t00_bytes = t00_p.read_bytes()
    # 2. the trial is queued (no r8_t00 fetched); the user picks ANOTHER interior off-winner pair
    preds = hpo_pick.load_search(tmp_path, ap)["design"]["fit"]["pair_predictions"]
    other = next(k for k, v in preds.items() if v.get("interior") and v.get("lr") is not None and k not in ("16:down", "16:mlp"))
    rank_b, set_b = other.split(":")
    rank_b = int(rank_b)
    assert hpo_pick.main(argv(rank_b, set_b)) == 0
    out = capsys.readouterr().out
    assert "reserved index 1: trial r8_t01, design r8_t01_trials.json, job suffix r8-t01" in out
    assert "supersedes the pending request t00 (rank 16 / set down" in out and "has NOT landed" in out
    assert "refuses to submit this one while that trial is still queued/running" in out
    b = json.loads(req_p.read_text())
    assert b == json.loads(t01_p.read_text())
    assert b["index"] == 1 and b["trial_id"] == "r8_t01" and b["design"] == "r8_t01_trials.json" and b["job_suffix"] == "r8-t01"
    assert b["pair"] == [rank_b, set_b] and b["request"] == t01_p.name
    assert b["predecessor"] == {"index": 0, "trial_id": "r8_t00", "design": "r8_t00_trials.json", "job_suffix": "r8-t00",
                                "request": t00_p.name, "pair": [16, "down"], "lr": a["pick"]["lr"], "landed": False}
    assert t00_p.read_bytes() == t00_bytes                                   # the reserved request is immutable
    assert hpo_pick.confirm_pick_ledger(tmp_path) == {0: a, 1: b}
    pick_rec = json.loads((tmp_path / "hpo_pick.json").read_text())["confirm_pick"]
    assert pick_rec["index"] == 1 and pick_rec["design"] == "r8_t01_trials.json" and pick_rec["job_suffix"] == "r8-t01"
    assert pick_rec["request"] == str(req_p) and pick_rec["request_file"] == str(t01_p) and pick_rec["predecessor"]["index"] == 0
    # 3. each design is emitted from its IMMUTABLE request and carries its own row index: two different trial dirs
    designs = {}
    for idx, src in ((0, t00_p), (1, t01_p)):
        out_p = tmp_path / f"r8_t{idx:02d}_trials.json"
        tune_arm.emit_trials(tune_arm.emit_args(confirm_pick_from=str(src), out=str(out_p), arm=ARM, config=cfg, si="constv2-mix-10m"))
        d8 = json.loads(out_p.read_text())
        assert d8["trials"][0]["index"] == idx and len(d8["trials"]) == 1
        c = d8["confirm_pick_of"]
        assert c["index"] == idx and c["trial_id"] == f"r8_t{idx:02d}" and c["design"] == f"r8_t{idx:02d}_trials.json"
        assert c["job_suffix"] == f"r8-t{idx:02d}" and c["request"] == str(src)
        assert f"r{d8['round']}_t{d8['trials'][0]['index']:02d}" == c["trial_id"]      # what run_trial writes
        designs[idx] = d8
    assert designs[0]["trials"][0]["lora_set_id"] == "down" and designs[0]["confirm_pick_of"]["predecessor"] is None
    assert (designs[1]["trials"][0]["lora_rank"], designs[1]["trials"][0]["lora_set_id"]) == (rank_b, set_b)
    assert designs[1]["confirm_pick_of"]["predecessor"]["trial_id"] == "r8_t00"
    # the two picks differ by PAIR (the additive design fit shares its argmin in u across pairs, so their inferred lrs may
    # coincide) — the identity that separates their trials is the reserved index, never the coordinates
    assert designs[1]["trials"][0]["lr"] == b["pick"]["lr"] and designs[0]["trials"][0]["lr"] == a["pick"]["lr"]
    assert (designs[0]["trials"][0]["lora_rank"], designs[0]["trials"][0]["lora_set_id"]) != (rank_b, set_b)
    # 4. the same pick again: the pending request stands, no new index
    assert hpo_pick.main(argv(rank_b, set_b)) == 0 and json.loads(req_p.read_text()) == b
    assert "already requested" in capsys.readouterr().out and not (tmp_path / hpo_pick.confirm_pick_request_name(2)).exists()
    # 5. back to pick A while B is pending: index 2 — never t00 again (that trial may be running under its own design)
    assert hpo_pick.main(argv(16, "down")) == 0
    c = json.loads(req_p.read_text())
    assert c["index"] == 2 and c["trial_id"] == "r8_t02" and c["predecessor"]["index"] == 1 and c["pair"] == [16, "down"]
    assert t00_p.read_bytes() == t00_bytes and json.loads(t01_p.read_text()) == b
    assert sorted(hpo_pick.confirm_pick_ledger(tmp_path)) == [0, 1, 2]
    # 6. a pre-ledger mirror (landed trial dirs, no ledger) is counted too; an empty / absent dir starts at 0
    legacy = tmp_path / "legacy"
    (legacy / "r8_t00").mkdir(parents=True)
    (legacy / "r8_t03").mkdir()
    assert hpo_pick.next_confirm_pick_index(legacy) == 4 and hpo_pick.next_confirm_pick_index(tmp_path / "nowhere") == 0
    assert hpo_pick.next_confirm_pick_index(legacy, {"index": 6}) == 7
    # 7. a request that reserves no index is refused by emit-trials (never defaulted to 0)
    bad = tmp_path / "bad_req.json"
    bad.write_text(json.dumps({k: v for k, v in a.items() if k != "index"}))
    with pytest.raises(SystemExit, match="reserves no integer index"):
        tune_arm.emit_trials(tune_arm.emit_args(confirm_pick_from=str(bad), out=str(tmp_path / "x.json"), arm=ARM, config=cfg, si="constv2-mix-10m"))
    # 8. a torn or hand-edited ledger refuses instead of guessing an index past it
    torn = tmp_path / hpo_pick.confirm_pick_request_name(7)
    torn.write_text("{not json")
    with pytest.raises(SystemExit, match="does not parse"):
        hpo_pick.confirm_pick_ledger(tmp_path)
    torn.write_text(json.dumps({**a, "index": 4}))
    with pytest.raises(SystemExit, match="not the index in its file name"):
        hpo_pick.next_confirm_pick_index(tmp_path)
    torn.unlink()


def test_hpo_trial_sbatch_derives_the_trial_dir_from_the_design_rows_index(tmp_path):
    """hpo_trial.sbatch:123 derived r<R>_t<NN> from $SLURM_ARRAY_TASK_ID while tune_arm.run_trial writes
    r<R>_t<trials[task].index> — a confirm-pick design (one row, reserved index 1, submitted --array 0-0) put its
    checkpoints and RESULT under r8_t00 and its summary under r8_t01. The wrapper now reads the row's index (as the
    sbatch runs it), refuses a task outside the design or a row without an index, and recon mode has no trial dir."""
    txt = (REPO / "scripts" / "sbatch" / "hpo_trial.sbatch").read_text()
    assert 'TRIAL_DIR="$(printf \'%s/r%s_t%02d\' "$HPO_ROOT" "$ROUND" "$TRIAL_IDX")"' in txt
    assert '"$ROUND" "$TASK")"' not in txt and '--index "$TASK"' in txt        # tune_arm still gets the task; the dir follows the row
    assert 'if [ "$MODE" != recon ]; then' in txt and '[ -n "$TRIAL_DIR" ] && [ -d "$TRIAL_DIR" ]' in txt
    assert '--checkpoint-dir "$TRIAL_DIR/ckpt"' in txt
    head = 'TRIAL_IDX="$("$PY" -c \''
    snippet = txt[txt.index(head) + len(head):]
    snippet = snippet[:snippet.index("' \"$TRIALS\" \"$TASK\" 2>&1)\"")]        # stderr is captured onto the FATAL log line
    design = tmp_path / "r8_t01_trials.json"
    design.write_text(json.dumps({"round": 8, "trials": [{"index": 1, "lr": 1e-4}]}))

    def run(path, task):
        return subprocess.run([sys.executable, "-c", snippet, str(path), str(task)], capture_output=True, text=True)

    r = run(design, 0)
    assert r.returncode == 0 and r.stdout.strip() == "1", r.stderr
    r = run(design, 1)
    assert r.returncode != 0 and "array task 1 is outside the design (1 trial row(s))" in r.stderr
    sixteen = tmp_path / "r1_trials.json"
    sixteen.write_text(json.dumps({"round": 1, "trials": [{"index": i} for i in range(16)]}))
    assert run(sixteen, 15).stdout.strip() == "15" and run(sixteen, 16).returncode != 0
    noidx = tmp_path / "noidx.json"
    noidx.write_text(json.dumps({"round": 8, "trials": [{"lr": 1e-4}]}))
    r = run(noidx, 0)
    assert r.returncode != 0 and "carries no integer index" in r.stderr


