    assert "clip gate: unconfirmed — no trial ran at these coordinates" in out
    assert "CONFIRM-PICK requested: rank 16 / set down" in out and "NOT promoted" in out
    assert (f"DRY-RUN: write {tmp_path / hpo_pick.confirm_pick_request_name(0)} and "
            f"{tmp_path / hpo_pick.CONFIRM_PICK_REQUEST_NAME}") in out            # the immutable reservation + the pointer
    assert "fit_lr_selected_by" not in out                    # nothing promoted: no fold entry, no config line
    assert not (tmp_path / "hpo_pick.json").exists() and not (tmp_path / hpo_pick.CONFIRM_PICK_REQUEST_NAME).exists()
    assert not (tmp_path / hpo_pick.confirm_pick_request_name(0)).exists()


