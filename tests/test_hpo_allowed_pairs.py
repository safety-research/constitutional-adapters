def _load(name, path):
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


hpo_table = _load("hpo_table", REPO / "scripts" / "sdfbase" / "hpo_table.py")
hpo_pick = _load("hpo_pick", REPO / "scripts" / "sdfbase" / "hpo_pick.py")

PARTIAL = [(r, s) for r in (4, 16, 64) for s in ("wo", "qkvo", "down")] + [(4, "mlp"), (16, "mlp")]
EXCLUDED = [(64, "mlp", "oom_at_R=128"), (4, "attn_mlp", "ceiling_S<1_at_L=49152"),
            (16, "attn_mlp", "ceiling_S<1_at_L=49152"), (64, "attn_mlp", "ceiling_S<1_at_L=49152")]


def _world(tmp_path):
    ap = write_allowed(tmp_path, PARTIAL, EXCLUDED)
    allowed = tune_arm.load_allowed_pairs(ap)
    payload = tune_arm.build_trials_v2(
        arm=ARM, model=MODEL, model_revision="0f", config_sha="c", position="all", round_no=1,
        lr_log10_box=BOX, allowed=allowed, warmup_frac=WF, max_grad_norm=CLIP,
        init_scheme="zero", n=16, seed=1)
    payload["search_id"] = "hpo-native:0123456789abcdef"
    (tmp_path / "r1_trials.json").write_text(json.dumps(payload))
    return ap, allowed, payload


def test_loader_normalises_and_refuses_bad_menus(tmp_path):
    ap, allowed, _ = _world(tmp_path)
    assert tune_arm.allowed_pair_keys(allowed) == PARTIAL
    assert [(e["rank"], e["set"]) for e in allowed["excluded"]] == [(r, s) for r, s, _ in EXCLUDED]
    assert tune_arm.set_order_for_pairs(allowed) == ["wo", "qkvo", "down", "mlp"]
    bad = tmp_path / "bad.json"
    bad.write_text(json.dumps({"pairs": [{"rank": 4, "set": "mlp"}], "excluded": [{"rank": 4, "set": "mlp", "reason": "x"}]}))
    with pytest.raises(SystemExit, match="BOTH allowed and excluded"):
        tune_arm.load_allowed_pairs(bad)
