def _metrics(d: Path, *, over: int, total: int = 10):
    """A trial's own metrics.jsonl: `over` of `total` optimizer steps with a pre-clip norm above the design's
    clip (CLIP = 1.3) — the clip-activation rate _trial_clip_activation reads is over / total."""
    rows = [{"step": i, f"{ARM}/grad_norm": (5.0 if i < over else 0.5)} for i in range(total)]
    (d / "metrics.jsonl").write_text("\n".join(json.dumps(r) for r in rows) + "\n")


def test_clip_gate_rules_by_name():
    g = tune_arm.clip_gate
    ok, why = g([])
    assert not ok and "no trial ran at these coordinates" in why and "inferred" in why
    ok, why = g([{"trial_id": "r9_t00", "status": "ok", "clip_activation_rate": None}])
    assert not ok and "no clip-activation measurement" in why
    ok, why = g([{"trial_id": "r9_t00", "status": "ok", "clip_activation_rate": 0.30}])
    assert not ok and "30.0% at r9_t00" in why and "over the 25% promotion limit" in why
    ok, why = g([{"trial_id": "r1_t02", "status": "nan_diverged", "clip_activation_rate": 0.1}])
    assert not ok and "no completed trial" in why
    ok, why = g([{"trial_id": "r1_t02", "status": "ok", "clip_activation_rate": 0.1},
                 {"trial_id": "r3_t00", "status": "ok", "clip_activation_rate": 0.2}])
    assert ok and "below the 25% limit" in why and "20.0%" in why
    ok, _ = g([{"trial_id": "r1_t02", "status": "ok", "clip_activation_rate": 0.1},
               {"trial_id": "r3_t00", "status": "ok", "clip_activation_rate": 0.25}])
    assert not ok                                             # AT the limit is over it (FD 6: > 25 % is not promotable)
    ok, _ = g([{"trial_id": "r1_t02", "status": "ok", "clip_activation_rate": 0.4}], threshold=0.5)
    assert ok


