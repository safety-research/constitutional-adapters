def test_a_partial_set_of_retained_trials_is_abandoned_and_every_trial_generated_under_the_attempt_contract(tmp_path, monkeypatch):
    seen: List[Any] = []
    monkeypatch.setattr("inspect_ai.eval_async", _fake_eval({0: _trial_log(), 1: _trial_log()}, seen))
    store = _Store(tmp_path / "cell")
    planted = _plant(store, 0)
    canned = _trial_log()
    # trial 0's pass log is reusable (a1's), trial 1's is not (a1 died there)
    monkeypatch.setattr(isv, "reusable_log", lambda log_dir, **kw: canned if log_dir.name.endswith("__s0") else None)
    summary = asyncio.run(isv.run_one_task(_ifeval_plan(), model=None, store=store, template={}, concurrency=4,
                                           emitter=_Emitter(), sampling_ref="abc123def456", attempt_scope=SCOPE_A2))
    assert [s[1] for s in seen] == [0, 1], "BOTH trials generated by a2 — trial 0 was NOT reused"
    assert summary["logs_reused"] == 0 and summary["n"] == 2
    assert not planted.exists() and (planted.parent / f"{planted.name}{isv.ABANDONED_LOG_SUFFIX}a2").is_file()
    assert completion.is_done(store.cell_dir, IFEVAL)
    marker = json.loads(completion.done_marker_path(store.cell_dir, IFEVAL).read_text())
    assert (marker["n_items"], marker["n_draws"], marker["n_expected_draws"]) == (2, 4, 4)


def test_without_an_attempt_scope_partial_reuse_is_unchanged_and_a_full_set_is_reused_whole(tmp_path, monkeypatch):
    seen: List[Any] = []
    monkeypatch.setattr("inspect_ai.eval_async", _fake_eval({0: _trial_log(), 1: _trial_log()}, seen))
    canned = _trial_log()
    monkeypatch.setattr(isv, "reusable_log", lambda log_dir, **kw: canned if log_dir.name.endswith("__s0") else None)
    store = _Store(tmp_path / "legacy")
    planted = _plant(store, 0)
    summary = asyncio.run(isv.run_one_task(_ifeval_plan(), model=None, store=store, template={}, concurrency=4,
                                           emitter=_Emitter(), sampling_ref="abc123def456"))
    assert [s[1] for s in seen] == [1] and summary["logs_reused"] == 1 and planted.exists()       # legacy: trial 1 alone
    # a FULL set under the attempt contract: reused whole, zero calls (a finalisation)
    seen.clear()
    monkeypatch.setattr(isv, "reusable_log", lambda log_dir, **kw: canned)
    store2 = _Store(tmp_path / "full")
    p0, p1 = _plant(store2, 0), _plant(store2, 1)
    summary2 = asyncio.run(isv.run_one_task(_ifeval_plan(), model=None, store=store2, template={}, concurrency=4,
                                            emitter=_Emitter(), sampling_ref="abc123def456", attempt_scope=SCOPE_A2))
    assert seen == [] and summary2["logs_reused"] == 2 and p0.exists() and p1.exists()


def test_a_missing_retry_log_beside_a_reused_pass_log_restarts_the_task_without_reuse(tmp_path, monkeypatch):
    """The rule's second door: both PASS logs reusable, the truncation-retry log of trial 0 missing -> the first task
    call would have mixed a1's pass evidence with a2's retry -> every retained log is set aside and the task runs whole."""
    seen: List[Any] = []

    async def fake_eval(task, **kwargs):                                     # a pass returns both items, a retry its one id
        _, _, idx = isv.current_request_identity()
        seen.append((isv._TASK.get(), idx, kwargs.get("max_tokens"), kwargs.get("sample_id")))
        ids = kwargs.get("sample_id") or ["1000", "1001"]
        return [_Log([_IfSample(i, _VALUE) for i in ids])]

    monkeypatch.setattr("inspect_ai.eval_async", fake_eval)
    monkeypatch.setattr(isv, "_retry_ids", lambda res: ["1000"] if len(res) == 2 else [])   # every PASS leaves one item to retry
    passes = {0: _trial_log(), 1: _trial_log()}
    calls = {"n": 0}

    def reusable(log_dir, **kw):
        calls["n"] += 1
        return passes.get(int(log_dir.name.rsplit("__s", 1)[1][:1])) if "__a2" not in log_dir.name else None

    monkeypatch.setattr(isv, "reusable_log", reusable)
    store = _Store(tmp_path / "retry")
    planted = [_plant(store, 0), _plant(store, 1)]
    summary = asyncio.run(isv.run_one_task(_ifeval_plan(retry_max_tokens=4096), model=None, store=store, template={},
                                           concurrency=4, emitter=_Emitter(), sampling_ref="abc123def456", attempt_scope=SCOPE_A2,
                                           route_virtual_model=VMODEL, max_model_len=65536))
    # both passes generated by a2 (after the restart), then their retries; nothing reused
    both = ["1000", "1001"]
    assert [(c[1], c[3]) for c in seen] == [(0, both), (0, ["1000"]), (1, both), (1, ["1000"])] and summary["logs_reused"] == 0
    assert all(not p.exists() and (p.parent / f"{p.name}{isv.ABANDONED_LOG_SUFFIX}a2").is_file() for p in planted)


def test_abandon_task_logs_renames_pass_and_retry_logs_of_every_trial_and_touches_nothing_else(tmp_path):
    store = _Store(tmp_path / "ab")
    p0, p1, r0 = _plant(store, 0), _plant(store, 1), _plant(store, 0, attempt=2)
    other = p0.parent / "notes.txt"
    other.write_text("kept")
    gone = isv.abandon_task_logs(store, IFEVAL, samples_per_item=2, attempt_id="a7")
    assert sorted(gone) == sorted(Path(f"{p}{isv.ABANDONED_LOG_SUFFIX}a7") for p in (p0, p1, r0))
    assert all(not p.exists() for p in (p0, p1, r0)) and other.read_text() == "kept"
    assert isv.reusable_log(p0.parent, expected_n=2) is None                 # invisible to every *.eval reader
    assert isv.abandon_task_logs(store, IFEVAL, samples_per_item=2, attempt_id="a8") == []


