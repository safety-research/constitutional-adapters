def _ifeval_plan(**kw):
    base = dict(row_task=IFEVAL, name="ifeval", task=object(), expected_n=2, samples_per_item=2,
                primary_scorer="instruction_following", max_tokens=2048, thinking=C.THINKING_OFF,
                item_set="ifeval541", sample_ids=["1000", "1001"], note="all-or-nothing test plan")
    base.update(kw)
    return isv.TaskPlan(**base)


def _trial_log():
    return _Log([_IfSample("1000", _VALUE), _IfSample("1001", _VALUE)])


def _plant(store, idx: int, attempt: int = 1) -> Path:
    d = C.inspect_log_dir(store.cell_dir, IFEVAL, idx, attempt)
    d.mkdir(parents=True, exist_ok=True)
    p = d / "2026-01-01T00-00-00_ifeval_retained.eval"
    p.write_bytes(b"retained log bytes")
    return p


