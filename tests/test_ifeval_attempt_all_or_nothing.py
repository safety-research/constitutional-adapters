"""ifeval-canonical-battery: a resume BETWEEN (or IN) the two trials produced a store the analysis
rejects — the ALL-OR-NOTHING reuse contract closes it.

Attempt a1 completed trial 0 and died in trial 1; a2 resumed, REUSED trial 0's `.eval` and generated trial 1; the runner
filed outcomes and completion for both trials, `contracts.resolve_attempt_kinds` accepted a2 alone (it sent task calls),
and I1 / I2 held a2's rows and records to EVERY draw: 1,082 outcomes vs 541 accepted requests, unrepairable by any
finalisation (a finalisation accepts the LATEST generation attempt — a2 again). The contract chosen (the brief's second
option): under ``--attempt-id`` a task's retained evidence is ONE attempt's — a PARTIAL set of retained trial logs is
abandoned whole (renamed ``*.eval.abandoned-<attempt>``, never deleted) and the resuming attempt generates every trial
(the same per-(item, trial) seeds — the same instrument); a full set is reused whole (a finalisation, as before); a
missing truncation-retry log beside a reused pass log triggers the same rule. Without an attempt scope nothing changes.
Proven at three levels: the runner's decision logic (patched reuse), a crash IN trial 1 through the REAL driver /
runner / provider against the loopback proxy + ledger followed by the resume, with the REAL producer completion and the
REAL I1 / I2 validators on the resulting store; and an ASYMMETRIC rung (2 draws in trial 0, 3 in trial 1) resumed after
a death between the trials.
"""
