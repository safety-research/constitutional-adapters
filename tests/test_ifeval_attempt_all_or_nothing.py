def _gates(root: Path, cell_dir: Path, *, cap: int, family_row: dict):
    manifest = json.loads((cell_dir / "manifest.json").read_text())
    summary0 = completion.read_task_summary(cell_dir, IFEVAL)
    # the producer records the client timeout in the SUMMARY (the field I1 reads), never in the manifest
    assert isv.CLIENT_TIMEOUT_FIELD in summary0 and "client_timeout_s" not in manifest and summary0[isv.CLIENT_TIMEOUT_FIELD] >= 7200.0
    recs = V.iter_jsonl(root / C.REQUEST_EVIDENCE_FILENAME)
    by_id, problem = V.evidence_index(recs)
    assert problem is None
    outcomes = completion.read_task_outcomes(cell_dir, IFEVAL)
    summary = completion.read_task_summary(cell_dir, IFEVAL)
    srow = C.sampling_for("llama8b", C.SAMPLING_VENDOR_PRESET)
    led = V.ledger_check(root / V.IC.LEDGER_FILENAME, header=outcomes, summary=summary, cap=cap, max_model_len=8192,
                         manifest=manifest, evidence_by_id=by_id)
    ledger_rows = V.iter_jsonl(root / V.IC.LEDGER_FILENAME)
    ev = V.request_evidence_check(root / C.REQUEST_EVIDENCE_FILENAME, ledger_rows=ledger_rows, row=family_row, srow=srow,
                                  n_draws=int(outcomes["n_attempted_samples"]), manifest=manifest, evidence_by_id=by_id)
    return manifest, led, ev, outcomes


def _crash_then_resume(world, monkeypatch, tmp_path, *, argv_extra: List[str], root: Path, n_trial0: int, fail_after: int | None):
    """a1 dies IN trial 1 — its real `eval_async` is CANCELLED once `fail_after` trial-1 requests were served (the
    faithful model of a killed process: a few trial-1 rows on the ledger, trial 1's log never completed, no failure
    storm; None = a1 dies BETWEEN the trials, before trial 1's first request) — then a2 resumes against the loopback."""
    from sisteer.capeval.serving import proxy as px
    routes = px.load_routing_table(world.table_path)["routes"]
    lb = _Loopback(routes, root / C.LEDGER_FILENAME)
    try:
        write_standup_endpoint(world.table_path, proxy_url=lb.proxy_url, max_model_len=8192, geometry=standup_geometry(8192, STANDUP_SEQS))
        write_ledger_endpoint(world.table_path, ledger_url=lb.ledger_url, upstream=lb.proxy_url)
        argv = list(world.argv)
        argv[argv.index("--proxy-url") + 1] = lb.proxy_url
        argv[argv.index("--controls") + 1] = C.CONTROL_IFEVAL
        argv[argv.index("--out-root") + 1] = str(root)
        argv.remove("--greedy")
        argv += [C.FLAG_LEDGER_URL, lb.ledger_url, C.FLAG_THINKING, C.THINKING_OFF, C.FLAG_SAMPLING, C.SAMPLING_VENDOR_PRESET,
                 C.FLAG_SAMPLES, "2", C.FLAG_TINYCAP_IDENTITY_VERSION, "2", *argv_extra]
        # --- a1: trial 0 completes for real; trial 1 dies ---
        import inspect_ai
        real_eval = inspect_ai.eval_async
        calls = {"n": 0}

        async def dying_eval(*a, **k):
            calls["n"] += 1
            if calls["n"] != 2:
                return await real_eval(*a, **k)
            if fail_after is None:
                raise RuntimeError("attempt a1 died between the trials (review S1 crash injection)")
            running = asyncio.ensure_future(real_eval(*a, **k))
            while not running.done() and lb.served_by_trial.get(1, 0) < fail_after:
                await asyncio.sleep(0.02)
            running.cancel()
            try:
                await running
            except (asyncio.CancelledError, Exception):
                pass
            raise RuntimeError("attempt a1 died IN trial 1 (review S1 crash injection: the process was killed mid-eval)")

        monkeypatch.setattr(inspect_ai, "eval_async", dying_eval)
        with pytest.raises((SystemExit, RuntimeError, Exception)):
            srun.main(argv + [C.FLAG_ATTEMPT_ID, "a1"])
        monkeypatch.setattr(inspect_ai, "eval_async", real_eval)
        cell_dir = _cell_dir(root)
        assert not completion.done_marker_path(cell_dir, IFEVAL).exists()
        trial0_dir = C.inspect_log_dir(cell_dir, IFEVAL, 0, 1)
        retained0 = sorted(trial0_dir.glob("*.eval"))
        assert len(retained0) == 1, "a1 left exactly trial 0's completed log"
        n_a1 = len(lb.chat_requests())
        assert n_a1 >= n_trial0
        # --- a2: resumes; the partial set is abandoned and BOTH trials generated by a2 ---
        lb.fail_trial = None
        srun.main(argv + [C.FLAG_ATTEMPT_ID, "a2"])
        return lb, argv, cell_dir, retained0, n_a1
    except BaseException:
        lb.close()
        raise
    finally:
        pass


@needs_dataset
def test_a_crash_in_trial_1_then_a_resume_gives_a_store_whose_accepted_attempt_holds_every_draw_and_passes_I1_I2(
        world, real_plan, monkeypatch, tmp_path):
    stub_framework_versions(monkeypatch)
    monkeypatch.setenv(C.INSPECT_API_KEY_ENV, "loopback-bearer")
    root = tmp_path / "pass1"
    n = len(real_plan.sample_ids)
    lb, argv, cell_dir, retained0, n_a1 = _crash_then_resume(world, monkeypatch, tmp_path, argv_extra=[], root=root, n_trial0=n, fail_after=5)
    try:
        # the abandoned a1 log is on disk, renamed; the DONE marker counts every draw
        assert not retained0[0].exists() and (retained0[0].parent / f"{retained0[0].name}{isv.ABANDONED_LOG_SUFFIX}a2").is_file()
        marker = json.loads(completion.done_marker_path(cell_dir, IFEVAL).read_text())
        assert (marker["n_items"], marker["n_draws"], marker["n_expected_draws"]) == (n, 2 * n, 2 * n)
        assert len(lb.chat_requests()) == n_a1 + 2 * n, "a2 generated BOTH trials (541 x 2 requests), reusing none of a1's"
        assert n_a1 > n, "a1 really died IN trial 1: it had served some trial-1 requests"
        row = G.row_for(G.matrix_rows(), "llama8b", "main", "none")
        manifest, led, ev, outcomes = _gates(root, cell_dir, cap=CAP1, family_row=row)
        assert manifest[C.MANIFEST_KEY_ACCEPTED_GENERATION_ATTEMPT] == "a2"
        kinds = {a["attempt_id"]: (a["kind"], a["terminal"]) for a in manifest[C.MANIFEST_KEY_RESUME_ATTEMPTS]}
        assert kinds == {"a1": ("generation", "interrupted"), "a2": ("generation", "completed")}
        assert manifest[C.MANIFEST_KEY_ATTEMPT_ATTRIBUTION]["a1"]["task_calls"] >= n
        # THE regression: I1 and I2 PASS — the accepted attempt's rows / records are exactly the 1,082 draws
        assert led["passed"], led["failures"]
        assert ev["passed"], ev["failures"]
        assert led["n_forwarded"] == 2 * n == led["n_draws"] and ev["n_task_records"] == 2 * n
        assert led["rows_by_attempt"]["a2"] == 2 * n and led["rows_by_attempt"]["a1"] >= n
        assert set(led["generation_span_by_attempt"]) == {"a1", "a2"}
    finally:
        lb.close()


@needs_dataset
def test_an_asymmetric_rung_resumed_after_a_death_between_its_trials_is_regenerated_whole_and_passes_I1_I2(
        world, real_plan, monkeypatch, tmp_path):
    """The rung's draws are ASYMMETRIC (2 in trial 0, 3 in trial 1); a1 completes trial 0's two draws and dies before
    trial 1; a2 abandons them and draws all five — the DONE marker over exactly the subset, I1 / I2 on a2 alone."""
    stub_framework_versions(monkeypatch)
    monkeypatch.setenv(C.INSPECT_API_KEY_ENV, "loopback-bearer")
    ids = list(real_plan.sample_ids)
    n_items = 40
    real = ids[:n_items]
    monkeypatch.setattr(G, "N", n_items)
    monkeypatch.setattr(G, "IDS", real)
    monkeypatch.setattr(G, "PROMPTS", [f"Synthetic instruction prompt {i}." for i in range(n_items)])
    monkeypatch.setattr(G, "N_INST", [1 + (i % 3) for i in range(n_items)])
    row = G.row_for(G.matrix_rows(), "llama8b", "main", "none")
    at_cap = {(0, 0), (1, 0), (2, 1), (3, 1), (4, 1)}                            # 5 of 80 draws > 1 %: escalate
    src_cell = G.build_store(tmp_path / "gen", row, at_cap=at_cap, cap=CAP1)
    record, subset = G.classify(src_cell.parents[1])
    assert record["exit"] == "escalate" and subset["n_draws"] == 5
    by_trial = {t: sorted(i for i, tt in subset["draws"] if tt == t) for t in (0, 1)}
    assert len(by_trial[0]) == 2 and len(by_trial[1]) == 3
    subset_path = G.write_rung_subset(tmp_path / "gen", row, subset, rung=CAP2)
    root = tmp_path / "rung4096"
    extra = [C.FLAG_MAX_TOKENS_BY_TASK, f"{C.IFEVAL_TASK_NAME}={CAP2}", C.FLAG_OFF_CAP_BY_TASK, f"{C.IFEVAL_TASK_NAME}={CAP2}",
             C.FLAG_ITEM_SUBSET, str(subset_path)]
    lb, argv, cell_dir, retained0, n_a1 = _crash_then_resume(world, monkeypatch, tmp_path, argv_extra=extra, root=root, n_trial0=2, fail_after=None)
    try:
        assert n_a1 == 2                                                         # a1: trial 0's two draws, then death
        assert len(lb.chat_requests()) == 2 + 5, "a2 drew all five, reusing neither of a1's two"
        assert not retained0[0].exists()
        marker = json.loads(completion.done_marker_path(cell_dir, IFEVAL).read_text())
        assert (marker["n_items"], marker["n_draws"], marker["n_expected_draws"]) == (5, 5, 5)
        from sisteer.capeval.tinycap import rung_probe as RP
        assert RP.draw_subset_task_reason(cell_dir, IFEVAL, draws=subset["draws"], cap=CAP2,
                                          source_identity_hash=subset["source_identity_hash"]) is None
        manifest, led, ev, outcomes = _gates(root, cell_dir, cap=CAP2, family_row=row)
        assert manifest[C.MANIFEST_KEY_ACCEPTED_GENERATION_ATTEMPT] == "a2"
        assert led["passed"], led["failures"]
        assert ev["passed"], ev["failures"]
        assert led["n_forwarded"] == 5 == led["n_draws"] and ev["n_task_records"] == 5 and led["rows_by_attempt"] == {"a1": 2, "a2": 5}
        assert sorted((i["item_id"], i["sample_idx"]) for i in outcomes["items"]) == sorted((i, t) for i, t in subset["draws"])
    finally:
        lb.close()
