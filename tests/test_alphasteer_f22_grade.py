def test_drift_is_computed_on_common_support_and_says_when_that_shrinks_the_sample():
    """A pass that abstains on part of the sample changes WHICH items each comparison covers. Differencing two rates
    over different item sets mixes drift with a composition change — and abstention concentrates on the degenerate
    stratum, so that change is not random with respect to what is being measured. The two headline rates keep their
    own full comparable sets; only the difference restricts to items with all three verdicts, and when that leaves
    less than two thirds of the sample the record says so rather than making a reader divide two fields."""
    import grade_alphasteer_f22 as g
    sampled = [{"item": ("d", "r", f"g{i}", f"t{i}"), "n_responses_represented": 1} for i in range(30)]
    filed = {it["item"]: 0.0 for it in sampled}
    fresh1 = {it["item"]: 0.0 for it in sampled}
    for i in (3, 4, 5, 6, 7, 8):              # 6 of 30: fresh1 disagrees with what was filed
        fresh1[sampled[i]["item"]] = 1.0
    fresh2 = dict(fresh1)                     # pass 2 agrees with pass 1 except where stated
    for i in (0, 1, 2):                       # 3 of 30: genuine fresh-vs-fresh disagreement
        fresh2[sampled[i]["item"]] = 1.0 if fresh1[sampled[i]["item"]] == 0.0 else 0.0
    for i in range(20, 30):                   # pass 2 abstains on a third of the sample
        del fresh2[sampled[i]["item"]]
    st = g.probe_stratum(sampled, fresh1, fresh2, filed, canonical=0.5)
    assert st["fresh_vs_filed"]["n_compared"] == 30 and st["fresh_vs_fresh"]["n_compared"] == 20
    dr = st["drift"]
    assert dr["n_drift_common_support"] == 20 and dr["n_fresh_vs_fresh"] == 20 and dr["n_fresh_vs_filed"] == 30
    assert dr["common_support_share_of_sample"] == pytest.approx(20 / 30)
    # on common support: 3 of 20 fresh-vs-fresh, 6 of 20 fresh-vs-filed -> +15 pp, not the -5 pp the raw rates give
    assert dr["fresh_vs_fresh_on_common_support"]["rate"] == pytest.approx(3 / 20)
    assert dr["fresh_vs_filed_on_common_support"]["rate"] == pytest.approx(6 / 20)
    assert dr["drift_pp"] == pytest.approx(15.0)
    naive = 100 * (st["fresh_vs_filed"]["disagreement_rate"] - st["fresh_vs_fresh"]["disagreement_rate"])
    assert naive == pytest.approx(5.0) and abs(naive - dr["drift_pp"]) > 5          # the mixing this prevents
    assert dr["discordant_fresh_vs_filed_only"] == 6 and dr["discordant_fresh_vs_fresh_only"] == 3
    # the FLAG travels with the figure: computed on the same shared items, never from the marginal intervals
    assert st["comparisons_disagree"] == dr["comparisons_disagree_on_common_support"]
    assert "does not prove a temporal cause" in st["comparisons_note"]
    assert "common_support_shrinkage_warning" not in dr                              # 2/3 exactly is not below 2/3
    for i in range(15, 20):                                                          # abstain on five more
        del fresh2[sampled[i]["item"]]
    st2 = g.probe_stratum(sampled, fresh1, fresh2, filed, canonical=0.5)
    assert st2["drift"]["n_drift_common_support"] == 15
    assert "below two thirds" in st2["drift"]["common_support_shrinkage_warning"]
    none_common = g.probe_stratum(sampled, fresh1, {}, filed, canonical=0.5)["drift"]
    assert none_common["status"] == "no_common_support" and "drift_pp" not in none_common


