def _degen_texts(n_clean, n_degen, *, prefix="g"):
    """{goal_id: [response]} with `n_degen` of the responses degenerate — the fixture is TEXT, the rate is derived."""
    out = {}
    for i in range(n_clean):
        out[f"{prefix}{i}"] = [f"I cannot help with that request, and here is a clean sentence number {i}."]
    for j in range(n_degen):
        out[f"{prefix}d{j}"] = [DEGENERATE_TEXTS[j % len(DEGENERATE_TEXTS)]]
    return out


