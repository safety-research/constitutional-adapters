def run_cap_condition(tmp_path, target, cell_name, summary, items, *, max_new=512, gens_by_control, capped_ids):
    """The WAVE's cap-conditioning step (`cap_condition.py` @ c88e3daa, by path, sha-pinned) run on a store laid out the way
    the driver leaves it; the tokenizer is stubbed to a whitespace tokenizer so `capped_ids` read as >= max_new-1 tokens."""
    if not CAPCOND.is_file():
        pytest.skip("the c88e3daa cap_condition.py is not present")
    assert hashlib.sha256(CAPCOND.read_bytes()).hexdigest() == gac.CAP_CONDITION_SHA256
    root = tmp_path / "controls_root"
    d = root / target / "cells" / cell_name
    (d / "private").mkdir(parents=True)
    write_json(d / "manifest.json", {"model_id": "m", "model_revision": "rev00000", "resolved_config": {"gen": {"max_new_tokens": max_new}}})
    write_json(d / "gen_stats.json", {c: {"n_total": len(g), "finish_reasons": {"length": sum(1 for i in g if i in capped_ids), "stop": sum(1 for i in g if i not in capped_ids)}}
                                      for c, g in gens_by_control.items()})
    write_json(d / "judge_summary.json", {**summary, "cell_id": cell_name.split("__controls__")[0]})
    with (d / "judge_items.jsonl").open("w") as f:
        for r in items:
            f.write(json.dumps(r, sort_keys=True) + "\n")
    for c, fname in (("xstest", "gens_xstest_v2.jsonl"), ("or_bench_hard_1k", "gens_or_bench_hard_1k.jsonl")):
        with (d / "private" / fname).open("w") as f:
            f.write(json.dumps({"header": True}) + "\n")
            for iid in gens_by_control[c]:
                text = " ".join(["tok"] * (max_new if iid in capped_ids else 40))
                f.write(json.dumps({"item_id": iid, "text": text}) + "\n")
    spec = importlib.util.spec_from_file_location("cap_condition", CAPCOND)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    class _WS:
        def __call__(self, texts, add_special_tokens=False):
            return {"input_ids": [t.split() for t in texts]}
    mod.tokenizer_for = lambda model_id, revision: _WS()
    argv = sys.argv
    sys.argv = ["cap_condition.py", "--root", str(root), "--targets", target]
    try:
        mod.main()
    finally:
        sys.argv = argv
    return d, json.loads((d / "judge_summary.json").read_text()), [json.loads(l) for l in (d / "judge_items.jsonl").read_text().splitlines() if l.strip()]


