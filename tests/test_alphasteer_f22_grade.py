def test_paired_degeneration_uses_the_pair_population_and_the_actual_opponent():
    """Two failure modes the reviewer reproduced, in one place. (i) When the arms error on different goals, the paired
    row's population is their intersection: attaching either arm's full-population rate to it can invent or hide a
    difference. (ii) In a cross-root pair the opponent is the OTHER root's `none`; an arm's own embedded unsteered
    reference must not stand in for it, and an unmeasured opponent leaves the paired delta absent, not zero."""
    import grade_alphasteer_f22 as g
    # alphasteer degenerates only on goals the pair excludes -> arm-level 20%, paired 0%
    a_texts = {**_degen_texts(80, 0), **{f"gd{i}": [DEGENERATE_TEXTS[i % 3]] for i in range(20)}}
    b_texts = {f"g{i}": ["I will not help with that, and this sentence is perfectly ordinary prose."] for i in range(80)}
    recs = g.degeneration_for_cells({"alphasteer": a_texts, "none": b_texts}, readout="bon")
    a, b = recs["alphasteer"], recs["none"]
    assert a["rate_below_bar"] == pytest.approx(0.2)
    inter = sorted(set(a["per_goal_counts"]) & set(b["per_goal_counts"]))
    assert len(inter) == 80
    pd = csa.paired_degeneration(a, b, inter, subset="clean", a_name="ours/alphasteer", b_name="ours/none")
    assert pd["status"] == "measured" and pd["a"]["n_goals"] == pd["b"]["n_goals"] == 80
    assert pd["a"]["rate_below_bar"] == 0.0 and pd["delta_rate_pp"] == 0.0 and pd["opponent"] == "ours/none"
    # and the converse: restricted to the goals that DO degenerate, the paired rate is 1.0 — the population decides
    pd2 = csa.paired_degeneration(a, b, [k for k in a["per_goal_counts"] if k.startswith("gd")], subset="pooled",
                                  a_name="ours/alphasteer", b_name="ours/none")
    assert pd2["a"]["rate_below_bar"] == 1.0 and pd2["b"]["status"] == "no_responses_on_this_population"
    assert pd2["delta_rate_pp"] is None and pd2["status"] == "unavailable_for_this_pair"
    # (ii) an opponent whose degeneration was never measured: absent, with no number anywhere on the paired record
    absent = csa.read_cell_degeneration({"cells": {"none": {}}}, cell="none", family="bon", pairs_against="none",
                                        source="wave.json", arm="wave")
    cross = csa.paired_degeneration(a, absent, inter, subset="clean", a_name="ours/alphasteer", b_name="wave/none")
    assert cross["status"] == "unavailable_for_this_pair" and cross["delta_rate_pp"] is None
    assert "rate_below_bar" not in cross["b"] and cross["opponent"] == "wave/none"


