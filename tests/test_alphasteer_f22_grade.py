def _prompt_bucket(user_text: str) -> int:
    return int(hashlib.sha256(user_text.encode()).hexdigest()[:8], 16) % 10


def _canned_text(user_text: str) -> tuple:
    """Deterministic canned served reply per prompt: bucket 0 -> at-cap (long, finish_reason 'length'); buckets 1-2 ->
    a marked jailbreak-style success; else a short benign reply."""
    b = _prompt_bucket(user_text)
    if b == 0:
        words = " ".join(f"{LONG_MARK} w{i} tok{i % 7}" for i in range(260))
        return words, "length"
    if b in (1, 2):
        return f"{JB_MARK} sure, here is a detailed answer to: {user_text[:40]}", "stop"
    return f"I can help a little with that: {user_text[:32]}", "stop"


def _canned_completion(payload, *, intervention_hash):
    user = next((m["content"] for m in reversed(payload.get("messages", [])) if m.get("role") == "user"), "")
    text, fr = _canned_text(user)
    n_out = len(text.split())
    return {"id": "chatcmpl-synthetic", "object": "chat.completion", "model": payload.get("model"),
            "choices": [{"index": 0, "message": {"role": "assistant", "content": text}, "finish_reason": fr}],
            "usage": {"prompt_tokens": 12, "completion_tokens": n_out, "total_tokens": 12 + n_out},
            "petri_intervention_hash": intervention_hash}


def _real_proxy_over_table(table_path, lens_mode):
    """The REAL server-side identity writer: a RoutingProxy built from a routing table, the vLLM transport stubbed
    (Backend is a Protocol of two async methods), attested `lens_reduction_mode` = lens_mode (None = not attested)."""
    from sisteer.capeval.serving import proxy as pm
    table = pm.load_routing_table(Path(table_path))

    class _Backend:
        async def chat_completions(self, payload):
            return _canned_completion(payload, intervention_hash="stub")

        async def tokenize(self, payload):
            return {"count": 12, "tokens": []}
    att = {pm.LENS_REDUCTION_MODE_KEY: lens_mode} if lens_mode is not None else {}
    proxy = pm.RoutingProxy(list(table["routes"]), _Backend(), base_model=table["base_model"], serving_mode=table["serving_mode"],
                            prompted_prefixes=list(table["prompted_prefixes"]), exact_replay_strategy=table["exact_replay_strategy"],
                            launch_attestation=att, base_revision=table.get("base_revision"))
    return table, proxy


def _stub_transport(monkeypatch, proxy, routes):
    """ONLY the HTTP layer of the REAL ProxyClientEngine is replaced: /models answers with the REAL proxy's `models_payload()`,
    /chat/completions with a canned completion carrying the route's intervention hash."""
