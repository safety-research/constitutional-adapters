def make_leg_dir(root: Path, *, mode: str, tag: str, families, job_id: str, sha: str, key: str, view: str, pulled=True) -> Path:
    """A serving dir named by the producer's rule (`<mode>_<TAG>_<fams '-'-joined>_<SLURM_JOB_ID>`, target_static.sbatch:47 /
    target_attacks.sbatch:37; `serving__` prefix from the lane's pull) with `standup_jobs.jsonl` in common.sh:267's field order."""
