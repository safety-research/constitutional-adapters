def test_reaggregation_verifies_n_goals_and_coverage_not_just_n_jailbroken(gated_tree):
    """The PRODUCER's block over a tree with a completed zero-response goal counts it (n_goals covers it, qtfs -1). A
    naive row-iterating map drops it while keeping n_jailbroken unchanged -> REFUSED by both readers; the
    per-goal-block reader on the producer's block verifies with that goal a failure."""
    t = gated_tree
    pub = t.published_block()                       # the producer's own emission (allow_errored: g038 excluded)
    uni = [g.goal_id for g in t.goals]
    zero, err = gid(39), gid(38)
    assert zero in pub["per_goal"] and pub["per_goal"][zero]["queries_to_first_success"] == -1 and pub["n_goals"] == 39
    assert pub["n_errored"] == 1 and pub["errored_goal_ids"] == [err] and err not in pub["per_goal"]
    # the join over the same tree, through the producer's loader + errored rule, reproduces the block
    responses, progress = load_gated_dir(t.defense_root)
    clean_ids, clean_responses, rep = glv.apply_errored_rule(responses, progress, uni, label="t")
    assert rep["errored_goal_ids"] == [err] and rep["n_graded"] == 39 and err not in clean_ids
    rec = glv.per_goal_from_rows(clean_ids, t.by_id, clean_responses, t.cache)
    assert len(rec["per_goal"]) == 39 and rec["per_goal"][zero]["n_responses"] == 0
    ver = glv.self_verify(rec, pub, family="pasttense", expected_universe=set(uni), errored_report=rep)
    assert ver["verified"] and ver["errored_goal_ids"] == [err] and ver["errored_report_agrees_with_published"]
    assert glv.compare_per_goal(rec, pub, family="pasttense")["agree"]
    # the NAIVE read: a map built from the response rows omits the zero-response goal; n_jailbroken unchanged -> REFUSED
    naive = {"per_goal": {g: v for g, v in rec["per_goal"].items() if g in clean_responses and clean_responses[g]}, "n_missing_verdicts": 0}
    assert sum(1 for v in naive["per_goal"].values() if v["queries_to_first_success"] > 0) == pub["n_jailbroken"]
    with pytest.raises(SystemExit) as ei:
        glv.self_verify(naive, pub, family="pasttense", expected_universe=set(uni), errored_report=rep)
    assert "n_goals recomputed 38 != published 39" in str(ei.value) and zero in str(ei.value)
    # the published-block reader: the producer's block verifies; a block missing the goal fails coverage though counts agree
    agg = published_aggregate({"alphasteer": pub}, attack="pasttense", target="gemma4e4b", n_expected=40)
