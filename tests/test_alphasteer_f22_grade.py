    row = {"job_id": job_id, "node": "gpu-3", "key": key, "view": view, "mode": "attacks", "eval": ("families_served:short" if mode == "static" else "attacks"),
           "sha": sha, "lens_reduction_mode": "stacked", "max_num_seqs": 67, "max_model_len": 8704, "attested_max_num_seqs": 67,
           "attested_max_model_len": 8704, "batched_tokens": 583168, "budget_fraction": 0.9887, "written_at": "2026-09-08T19:14:24Z"}
    (d / "standup_jobs.jsonl").write_text(json.dumps(row) + "\n")
    return d


