class FakeLiveGrader:
    """Stands in for `LiveStrongREJECTGrader` INSIDE the real grader: the same attributes the grader reads (`rubric`,
    `_sr_kind`, `_cache`, `_gate`, `_client`) with the REAL `ScoreCache` (the cache file's real writer) and the REAL
    `AdaptiveGate`; `grade` is cache-first and otherwise judges by a fixed rule on the response text (a response carrying
    JB_MARK is a full non-refusal), FILING the verdict through the real ScoreCache.put exactly as the live grader does.
    No API. Everything the grader writes is written by the grader's own code."""

    def __init__(self, *, model, concurrency, cache_path, allow_unscored=0, **_):
        from grade_bon_live import ScoreCache
        from sisteer.throttle import AdaptiveGate
        self.rubric, self._sr_kind, self.model = "v1", "sr", model
        self._cache = ScoreCache(Path(cache_path), judge_model=model)
        self._gate = AdaptiveGate(concurrency)
        self.org, self.concurrency = _.get("org", "lowprio"), concurrency
        # a vault-built client carries its pool stamp (the placeholder is not a key); the driver records it
        self._client = SimpleNamespace(base_url="https://api.anthropic.com",
                                       sisteer_pool_stamp=vault.pool_stamp(self.org, "ORG-KEY-PLACEHOLDER"))

    @property
    def pool_stamp(self):
        return vault.client_pool_stamp(self._client)

    def run_stats(self):
        return {**self.pool_stamp, "org": self.org, "concurrency": self.concurrency, "sdk_max_retries": 2,
                "n_rate_limited": self._gate.n_rate_limited, "in_flight_ceiling": self._gate.live}

    def grade(self, items):
        from grade_bon_live import strongreject_score_from_rubric
        out = {}
        for it in items:
            key = _live_cache_key("sr", *it)
            v = self._cache.get(key)
            if v is None:
                v = {"refused": 0 if JB_MARK in it[3] else 1, "convincing": 5, "specific": 5}
                self._cache.put(key, v)
            out[it] = strongreject_score_from_rubric(int(v["refused"]), int(v["convincing"]), int(v["specific"]))
        return out


