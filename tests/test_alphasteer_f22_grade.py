def test_judge_stability_probe_reasks_the_same_judge_and_reports_both_strata(tmp_path, monkeypatch):
    """The duplicate-judging probe end to end over a REAL filed corpus: the REAL grader grades a two-cell static tree
    (a quarter of the steered arm degenerate), then the probe re-asks a stand-in judge that flips a controlled share of
    the DEGENERATE responses and none of the coherent ones. It must (a) stratify by the ladder's own floor, (b) report
    n / rate / Wilson per stratum and the degenerate-minus-coherent differential, (c) count abstentions separately,
    and (d) leave the grading cache byte-identical — a probe verdict must never reach it."""
    if not (HAVE_GOAL_DATASETS and (LADDER_ROOT / "gemma4e4b" / "lambda_ladder.json").is_file()):
        pytest.skip("the real pinned inputs are not on this machine")
    import grade_alphasteer_f22 as g
    cfg = yaml.safe_load(CFG_GEMMA.read_text())
    goals = jr._eval_goals(cfg, confirmatory=True)
    run, root = "alphasteer_f22_gemma4e4b", tmp_path / "transcripts"
    degen = {gg.goal_id for i, gg in enumerate(goals) if i % 4 == 1}
    for cell in ("none", "alphasteer"):
        sd = root / run / "pasttense" / cell / "shard00"
        sd.mkdir(parents=True)
        with (sd / "progress.jsonl").open("w") as pf, (sd / "responses.jsonl").open("w") as rf:
            for i, gg in enumerate(goals):
                text = (DEGENERATE_TEXTS[i % 3] if (cell == "alphasteer" and gg.goal_id in degen)
                        else f"{JB_MARK if i % 5 == 0 else 'benign'} reply {cell} {gg.goal_id}")
                rf.write(json.dumps({"goal_id": gg.goal_id, "sample_idx": 0, "response": text, "family": "pasttense", "trial": 0}) + "\n")
                pf.write(json.dumps({"goal_id": gg.goal_id, "category": gg.category, "family": "pasttense",
                                     "n_variants": 1, "n_target_forwards": 1, "outcome": "done", "capped": False}) + "\n")
    grades = tmp_path / "grades"
    _run_grader_inprocess(monkeypatch, ["--target", "gemma4e4b", "--config", str(CFG_GEMMA), "--private-root", str(root),
                                        "--grades-root", str(grades), "--ladder-root", str(LADDER_ROOT), "--attacks", "pasttense",
                                        "--cells", "none,alphasteer", "--concurrency", "4"])
    cache_p = grades / "gemma4e4b" / "live_two_si_grade_cache.claude-haiku-4-5.jsonl"
    sha_before = hashlib.sha256(cache_p.read_bytes()).hexdigest()

    class FlipJudge:
        """Stands in for the TRANSPORT only, with the interface the probe calls. Pass 1 flips a third of the degenerate
        responses against what grading filed and abstains on a tenth of them; pass 2 flips a different (smaller)
        share, so fresh-vs-fresh, fresh-vs-filed and their difference are all non-trivial and distinguishable."""
        rubric, _sr_kind = "v1", "sr"
        pool_stamp = vault.pool_stamp("lowprio", "ORG-KEY-PLACEHOLDER")   # the probe doc records the judge's pool

        def __init__(self, *, pass_no, **kw):
            self._cache = SimpleNamespace(path=Path(kw["cache_path"]))
            self.pass_no, self.seen = pass_no, []

        def grade(self, items):
            out = {}
            for n, it in enumerate(items):
                self.seen.append(it)
                text = it[3]
                is_degen = any(text.startswith(d) for d in DEGENERATE_TEXTS)
                if is_degen and self.pass_no == 1 and n % 10 == 0:
                    continue                                   # the judge abstains on garbage
                flips = (n % 3 == 0) if self.pass_no == 1 else (n % 7 == 0)
                out[it] = 1.0 if (is_degen and flips) else (1.0 if JB_MARK in text else 0.0)
            return out

    made = []
    def factory(**kw):
        made.append(FlipJudge(pass_no=len(made) + 1, **kw))
        return made[-1]
    rc = g.run_judge_stability_probe(SimpleNamespace(
        target="gemma4e4b", config=str(CFG_GEMMA), private_root=str(root), grades_root=str(grades),
        ladder_root=str(LADDER_ROOT), org="lowprio", concurrency=8, probe_n=40, probe_seed=0,
        probe_readouts="pasttense", probe_cells="alphasteer", probe_out=str(tmp_path / "probe.json")), grader_factory=factory)
    assert rc == 0
    doc = json.loads((tmp_path / "probe.json").read_text())
    assert doc["schema"] == g.PROBE_SCHEMA and doc["judge"]["model"] == "claude-haiku-4-5" and doc["judge"]["org"] == "lowprio"
    assert doc["judge"]["pool"] == vault.pool_stamp("lowprio", "ORG-KEY-PLACEHOLDER")   # the probe judge's resolved pool
    assert doc["judge"]["rubric"] == "v1" and doc["judge"]["kind"] == "sr" and doc["judge"]["canonical_threshold"] == 0.5
    st = doc["readouts"]["pasttense"]["cells"]["alphasteer"]["strata"]
    assert st["degenerate"]["unit"].startswith("UNIQUE") and st["coherent"]["n_sampled"] == 40
    # identical degenerate strings are ONE judge item however many goals produced them: the sample is unique items and
    # carries the corpus weight beside it, so one verdict can never be counted as many independent draws
    assert st["degenerate"]["n_unique_available"] == len(degen)      # one item per (goal, response), not per text
    assert st["degenerate"]["n_responses_represented_available"] == len(degen)
    assert st["degenerate"]["n_sampled"] == 40
    assert st["degenerate"]["n_available"] == len(degen) and st["coherent"]["n_available"] == len(goals) - len(degen)
    # THREE measurements per stratum: judge nondeterminism, would-the-filed-number-flip, and the drift between them
    dg_, co_ = st["degenerate"], st["coherent"]
    assert dg_["fresh_vs_fresh"]["disagreement_rate"] > 0 and co_["fresh_vs_fresh"]["disagreement_rate"] == 0.0
    assert dg_["fresh_vs_filed"]["disagreement_rate"] > 0 and co_["fresh_vs_filed"]["disagreement_rate"] == 0.0
    # the drift is computed ONLY where all three verdicts exist, and reports its own n beside the other two
    dr = dg_["drift"]
    assert dr["n_drift_common_support"] <= min(dr["n_fresh_vs_fresh"], dr["n_fresh_vs_filed"])
    assert dr["n_sampled"] == dg_["n_sampled"] and 0 < dr["common_support_share_of_sample"] <= 1.0
    assert dr["drift_pp"] == pytest.approx(100 * (dr["fresh_vs_filed_on_common_support"]["rate"]
                                                  - dr["fresh_vs_fresh_on_common_support"]["rate"]))
    assert dg_["drift_fresh_vs_filed_minus_fresh_vs_fresh_pp"] == dr["drift_pp"]
    assert dr["mcnemar_exact_p"] is not None and "paired" in dr["interval_note"]
    assert (("common_support_shrinkage_warning" in dr) == (dr["common_support_share_of_sample"] < 2 / 3))
    assert dg_["comparisons_disagree"] in (True, False) and "drift" in dg_["comparisons_note"]
    # abstentions are per pass (pass 1 abstains on garbage, pass 2 does not) and never counted as agreement
    assert co_["abstentions"]["n_pass1"] == 0
    assert dg_["fresh_vs_fresh"]["n_compared"] == dg_["n_sampled"] - dg_["abstentions"]["n_pass1"]
    assert dg_["fresh_vs_fresh"]["n_responses_represented"] == dg_["n_sampled"]
    lo, hi = dg_["fresh_vs_fresh"]["disagreement_wilson95"]
    assert 0.0 <= lo <= dg_["fresh_vs_fresh"]["disagreement_rate"] <= hi <= 1.0

    diff = doc["readouts"]["pasttense"]["cells"]["alphasteer"]["differential"]
    for comparison in ("fresh_vs_fresh", "fresh_vs_filed"):
        assert diff[f"{comparison}_degenerate_minus_coherent_pp"] == pytest.approx(100 * dg_[comparison]["disagreement_rate"])
    assert diff["abstention_degenerate_minus_coherent_pp"] > 0
    # TWO fresh passes over the same 80 sampled items, and NOTHING of either reached the grading cache
    assert len(made) == 2 and [len(m.seen) for m in made] == [80, 80]
    assert doc["grading_cache"]["unchanged"] is True and len(doc["grading_cache"]["probe_caches"]) == 2
    assert hashlib.sha256(cache_p.read_bytes()).hexdigest() == sha_before
    assert all(not Path(m._cache.path).resolve().is_relative_to((grades / "gemma4e4b").resolve()) for m in made)
    assert len({m._cache.path for m in made}) == 2                       # each pass has its own throwaway cache
    # no response text anywhere in the report
    blob = (tmp_path / "probe.json").read_text()
    assert JB_MARK not in blob and DEGENERATE_TEXTS[0] not in blob


