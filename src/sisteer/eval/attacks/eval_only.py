"""Corpora the repository ships for evaluation only: replayed against a model, never trained on.

One corpus is in this class today: the ReNeLLM paper corpus (:data:`sisteer.eval.attacks.renellm.SHIPPED_CORPUS`), 777
rewrites generated by a third-party model (x-ai/grok-4.5 through OpenRouter) and shipped under its own terms
(:data:`sisteer.eval.attacks.renellm.CORPUS_TERMS`), not under the repository's MIT licence. Those terms permit research and
evaluation use and forbid using the rows to train, fine-tune or otherwise improve any AI system.

Evaluation replay reads it (``renellm.run_renellm``). Every training-side reader refuses it, before anything is written:

* training-pool sampling (``sisteer.sampling.sources``: the families' ``training_variants`` lookups and the inventory's
  prompts; ``scripts/pool_sample.py``'s cached inventory)
* the training-pool builder (``sisteer.eval.matched_pool.build_matched_pool``)
* the held-out leakage gate's training fingerprint (``heldout_leakage.load_training_fingerprint``)
* the training stage's pair loader (``scripts/train_two_si_objects.py``)
* the package's pairs loader (``sisteer.data.pairs.load_pairs``), which the pipeline's pair-trained methods read

A reader refuses the corpus by PATH (the shipped copy, through any symlink), by FILE BYTES (its sha256), by CONTENT (the
canonical row hash :func:`sisteer.eval.attacks.frozen_corpus.corpus_content_hash`, which survives re-serialising and
re-ordering) and, as a backstop for a copy in any other form (a subset, prompts carried into a store or a pairs file), by the
hash of each prompt, exact and normalised (``jailbreak_data.normalized_text_sha``). Refusals name counts and hashes only, never
a prompt.

Standard library only: the cluster job scripts import ``renellm`` (which imports this module) under a bare system python.
"""

from __future__ import annotations

import hashlib
import json
import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Optional

#: the repository root (``src/sisteer/eval/attacks/eval_only.py`` -> four parents up)
REPO = Path(__file__).resolve().parents[4]


@dataclass(frozen=True)
class EvalOnlyCorpus:
    """One evaluation-only corpus: where the repository ships it, its two hashes, and the terms it ships under."""

    name: str
    path: str               # repo-relative (an absolute path is taken as is)
    content_hash: str       # frozen_corpus.corpus_content_hash over its rows
    file_sha256: str        # sha256 of the file's bytes
    terms: str              # repo-relative terms file
    generator: str          # what generated the rows

    @property
    def abspath(self) -> Path:
        return REPO / self.path


class EvalOnlyCorpusRefused(RuntimeError):
    """A training-side reader met an evaluation-only corpus. Raised before anything is written."""


class EvalOnlyCorpusAltered(RuntimeError):
    """The repository's copy of an evaluation-only corpus does not hash to its pin, so the prompt-level check cannot trust it."""


def corpora() -> tuple[EvalOnlyCorpus, ...]:
    """Every evaluation-only corpus, built from the owning family's pins (read at call time, so the family module stays the
    one place its hashes are written)."""
    from . import renellm

    return (EvalOnlyCorpus(name="the ReNeLLM paper corpus", path=renellm.SHIPPED_CORPUS,
                           content_hash=renellm.PINNED_SHA, file_sha256=renellm.PINNED_FILE_SHA256,
                           terms=renellm.CORPUS_TERMS, generator=renellm.CORPUS_GENERATOR),)


def _message(corpus: EvalOnlyCorpus, consumer: str, evidence: str) -> str:
    return (f"{consumer}: refused {corpus.name} ({corpus.path}, content hash {corpus.content_hash}): {evidence}. It is "
            f"{corpus.generator} output that the repository ships for evaluation only, under {corpus.terms}, which forbid "
            "using it to train, fine-tune or otherwise improve any AI system; no training pool, leakage fingerprint or "
            "training stage may read it, and evaluation replay (the renellm attack) is its only use. Refused before "
            "anything was written.")


def _same_file(a: Path, b: Path) -> bool:
    try:
        return os.path.samefile(a, b)
    except OSError:
        return a.expanduser().resolve() == b.expanduser().resolve()


def match_path(path) -> Optional[EvalOnlyCorpus]:
    """The evaluation-only corpus whose shipped copy ``path`` is (directly, or through a symlink or hard link), or None."""
    p = Path(path)
    for corpus in corpora():
        if _same_file(p, corpus.abspath):
            return corpus
    return None


def _content_hash_of(raw: bytes) -> Optional[str]:
    """The canonical content hash of ``raw`` when it reads as frozen-corpus JSONL rows, else None. Only the first non-empty line
    is read before deciding, so a pairs file, a store or any other shape costs one line, never a parse of a large file."""
    need = {"goal_id", "sample_idx", "variant_name", "prompt"}
    start = 0
    while True:
        end = raw.find(b"\n", start)
        line = raw[start:] if end < 0 else raw[start:end]
        if line.strip():
            break
        if end < 0:
            return None
        start = end + 1
    try:
        first = json.loads(line.decode("utf-8"))
        if not isinstance(first, dict) or not need <= set(first):
            return None
        rows = [json.loads(ln) for ln in raw.decode("utf-8").splitlines() if ln.strip()]
        from .frozen_corpus import corpus_content_hash

        return corpus_content_hash(rows)
    except (ValueError, KeyError, TypeError):
        return None


def refuse_corpus(*, consumer: str, path=None, raw: Optional[bytes] = None, file_sha256: Optional[str] = None,
                  content_hash: Optional[str] = None) -> None:
    """Refuse when what a training-side reader is about to read is an evaluation-only corpus: ``path`` is a shipped copy;
    or its bytes (``raw``, else read from ``path`` when it is a file), ``file_sha256`` or ``content_hash`` are an
    evaluation-only corpus's. Give whatever the caller already has; a missing path refuses nothing by itself."""
    where = f"{path}" if path is not None else "the corpus"
    if path is not None:
        hit = match_path(path)
        if hit is not None:
            raise EvalOnlyCorpusRefused(_message(hit, consumer, f"{path} is its shipped copy"))
        if raw is None and file_sha256 is None and Path(path).is_file():
            raw = Path(path).read_bytes()
    if raw is not None and file_sha256 is None:
        file_sha256 = hashlib.sha256(raw).hexdigest()
    if raw is not None and content_hash is None:
        content_hash = _content_hash_of(raw)
    for corpus in corpora():
        if file_sha256 is not None and file_sha256 == corpus.file_sha256:
            raise EvalOnlyCorpusRefused(_message(corpus, consumer, f"{where} holds its bytes (file sha256 {file_sha256})"))
        if content_hash is not None and content_hash == corpus.content_hash:
            raise EvalOnlyCorpusRefused(_message(corpus, consumer, f"{where} holds its rows (content hash {content_hash})"))


#: ``(corpus path, file sha256) -> (exact prompt shas, normalised prompt shas)``, read once per process
_PROMPT_SHAS: dict[tuple[str, str], tuple[frozenset, frozenset]] = {}
#: shipped copies found absent, announced once per process
_ABSENT_ANNOUNCED: set[str] = set()


def _text_sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def prompt_shas(corpus: EvalOnlyCorpus) -> tuple[frozenset, frozenset]:
    """The exact and normalised sha256 of every prompt in ``corpus``'s shipped copy. Empty (announced once on stderr) when the
    copy is absent, since the path and hash checks still stand; :class:`EvalOnlyCorpusAltered` when it does not hash to its pin."""
    key = (str(corpus.abspath), corpus.file_sha256)
    if key in _PROMPT_SHAS:
        return _PROMPT_SHAS[key]
    p = corpus.abspath
    if not p.is_file():
        if key[0] not in _ABSENT_ANNOUNCED:
            _ABSENT_ANNOUNCED.add(key[0])
            print(f"[eval-only] {corpus.name} is absent at {p}, so the prompt-level training check cannot run; the path, "
                  "file-hash and content-hash checks still apply.", file=sys.stderr, flush=True)
        return frozenset(), frozenset()
    raw = p.read_bytes()
    got = hashlib.sha256(raw).hexdigest()
    if got != corpus.file_sha256:
        raise EvalOnlyCorpusAltered(
            f"{p} hashes to {got}, not to {corpus.name}'s pinned sha256 {corpus.file_sha256}: the repository's copy was "
            f"altered. Restore it (git checkout -- {corpus.path}); the training-side checks refuse to run on it.")
    from ..jailbreak_data import normalized_text_sha

    exact, norm = set(), set()
    for line in raw.decode("utf-8").splitlines():
        if not line.strip():
            continue
        prompt = json.loads(line).get("prompt")
        if isinstance(prompt, str) and prompt:
            exact.add(_text_sha(prompt))
            norm.add(normalized_text_sha(prompt))
    _PROMPT_SHAS[key] = (frozenset(exact), frozenset(norm))
    return _PROMPT_SHAS[key]


def refuse_texts(texts: Iterable, *, consumer: str) -> int:
    """Refuse when any of ``texts`` is a prompt of an evaluation-only corpus (exact, or after ``normalized_text_sha``'s
    case and whitespace folding). Non-strings are skipped. Returns how many texts were checked."""
    from ..jailbreak_data import normalized_text_sha

    tables = [(corpus, *prompt_shas(corpus)) for corpus in corpora()]
    tables = [t for t in tables if t[1]]
    checked = 0
    hits: dict[str, int] = {}
    for text in texts:
        if not isinstance(text, str) or not text:
            continue
        checked += 1
        if not tables:
            continue
        exact, norm = _text_sha(text), None
        for corpus, ex, nm in tables:
            if exact in ex:
                hits[corpus.name] = hits.get(corpus.name, 0) + 1
                continue
            norm = norm or normalized_text_sha(text)
            if norm in nm:
                hits[corpus.name] = hits.get(corpus.name, 0) + 1
    if hits:
        corpus = next(c for c in corpora() if c.name in hits)
        raise EvalOnlyCorpusRefused(_message(corpus, consumer, f"{hits[corpus.name]} of the {checked} prompts it was given "
                                                               "are its rows"))
    return checked
