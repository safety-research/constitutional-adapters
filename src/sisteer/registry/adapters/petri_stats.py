                batch.add("run_state", {"run_id": rid, "state": "judged", "event_utc": when, "evidence_kind": "completion_artifact",
                                        "evidence_uri": stats_src[(view, cid)][0] if s else agg_src[(view, cid)][0]}, producer, now, observe=False)
                # metrics
                if kind == "pooled":
                    mom = (s or {}).get("mean_of_behavior_means")
                    if mom is None and agg_beh:
                        vals = [(agg_beh.get(b) or {}).get("mean", {}).get(b) for b in BEHAVIOURS]
                        vals = [v for v in vals if v is not None]
                        mom = sum(vals) / len(vals) if vals else None
                    # the sidecar's pooled paired block is a comparison of the read: decided by the anchor currency BEFORE the metric row
                    # is added (a park lands on the row's `extra.delta_block`, and the record id is minted over the payload at add time)
                    metric_extra: Dict[str, Any] = {}
                    contrast: Optional[Dict[str, Any]] = None
                    vbc = vs_bare_cell_legacy.get((view, cid))
                    if vbc and vbc.get("delta") is not None:
                        anchor_rid = self._anchor_run(view, run_key_of, stats, agg, anchors, stats_src.get((view, cid), ("", "", ""))[2], inputs, eval_id, inst_row)
                        sidecar = {"delta": vbc.get("delta"), "delta_lo": vbc.get("delta_lo"), "delta_hi": vbc.get("delta_hi"), "delta_p": vbc.get("sign_test_p"),
                                   "delta_method": f"paired mean difference over {vbc.get('n')} shared (behaviour, scenario) items, percentile bootstrap "
                                                   f"{vbc.get('n_boot')} draws (sidecar vs_bare_cell)", "effect_size": vbc.get("d_z"), "effect_kind": "dz",
                                                   "n_pairs": LC.int_or_none(vbc.get("n")) or 0,
                                   "extra": {"d_z_lo": vbc.get("d_z_lo"), "d_z_hi": vbc.get("d_z_hi"), "sign": "cell minus unsteered (positive = MORE of the behaviour)",
                                             "n_per_behavior": vbc.get("n_per_behavior"), "caveat": vbc.get("caveat")}}
                        contrast, park, refusal = self._decide_contrast(ctx, run=p, rid=rid, jid=jid, judge_id=judge_id, eval_id=eval_id, inst_row=inst_row,
                                                                        standup=view, own_anchor_rid=anchor_rid, sidecar=sidecar, when=when)
                        metric_extra["delta_block"] = park
                        if refusal:
                            self.refusals.add(f"{key}|{eval_id}|contrast", refusal)
                    if mom is not None:
                        batch.add("run_metric", {"run_id": rid, "judgment_id": jid, "metric_id": METRIC, "threshold": THRESHOLD, "computation_id": "",
                                                 "producer_metric_spelling": "mean_of_behavior_means", "value": mom, "n": audited, "ci_method": "none filed (mean of the six behaviour means)",
                                                 "computed_by": "producer", "computed_utc": when, "source_uri": (stats_src[(view, cid)][0] if s else agg_src[(view, cid)][0]),
                                                 "source_producers_json": producers, "extra": metric_extra}, producer, now)
                        n_metrics += 1
                    if contrast is not None:
                        batch.add("run_contrast", contrast, producer, now)
                        n_contrasts += 1
                    # every (behaviour, scenario) item under the pooled run too, so the pooled contrast can be re-derived from items
                    for b, bb in per_beh.items():
                        for sc, score in (bb.get("per_scenario") or {}).items():
                            batch.add("item_result", {"run_id": rid, "item_id": f"{b}/{sc}", "metric_id": "petri_score", "trial_index": 0, "sample_index": 0,
                                                      "turn_index": -1, "judgment_id": jid, "value": score, "label": None, "api_pool": None, "created_utc": when,
                                                      "judged_utc": when, "withdrawn_by_revision_id": None}, producer, now)
