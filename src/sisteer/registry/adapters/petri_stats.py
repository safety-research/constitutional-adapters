"""`petri_stats` adapter: the Petri per-scenario read-outs and the aggregate → runs, items, contrasts.

Two producers describe one audit: `petri_agg.json` (behaviour means, completion — regenerated by `agg_petri.py`,
now a durable file) and the `petri_stats/*.json` sidecars (per-scenario scores, paired contrasts, intervention
hashes — regenerated on demand). Per (view, cell) the two must name the SAME `petri_run_key`; a disagreement REFUSES
the cell (the export's guard, kept and made per row), and every metric records both producers in
`source_producers_json`. The run identity is one run per (behaviour eval, cell) plus the pooled eval, all under
the audit's run key with `<view>:<cell>` as the object discriminator (S1). Item rows are one per (behaviour, scenario)
transcript score (`turn_index = -1`, `item_id = <behaviour>/<scenario>`; scenario ids are the bundle's scenario
NAMES, never transcript text). Contrasts are the sidecar's own paired blocks (`vs_bare`, `vs_bare_cell`) against the
view's audited `none` (the anchor the file names). The Petri harness's path-matched no-op controls (`none__lens0`)
are DERIVED legs and are not runs (legacy_spellings.yaml).

Every contrast is DECIDED by the pass's anchor currency (:mod:`anchor_current`): the audited `none`
this reader composes is the OWN anchor, kept when it is a current unsteered run of the exact key with one usable `petri_score` reading
under the Petri judge (the sidecar's paired block files, plus ``extra.anchor_selection``); an own anchor the registry retired, or one it
never folded (a `none` row this read refused, still named by the sidecar's anchor block), is a reason not to use THAT id, never a
dependency block -- the exact-key search runs, and a current unsteered run of this source (same standup, else another) or the paper's
roster-matched baseline re-anchors the comparison with the REGISTRY's statistic: the sidecar's deltas are producer-filed against the
producer's own `none`, so a re-picked contrast is the per-behavior PAIRED difference over both runs' registry item rows
(:func:`declared_common.paired_items_contrast`: the mean over behaviors of each behavior's mean per-scenario difference over the scenarios
judged on both sides -- the filed `mean_of_behavior_means` weighting -- a stratified bootstrap, a sign test, dz; a behavior with no shared
scenario refuses by name), under its own `computation` row, the sidecar's block parked on the metric row's ``extra.delta_block``. No current
anchor at the exact key parks the comparison by name and its previous key is withdrawn by the head.
"""
