    def _decide_contrast(self, ctx: AdapterContext, *, run: Mapping[str, Any], rid: str, jid: str, judge_id: Optional[str], eval_id: str,
                         inst_row: Mapping[str, Any], standup: str, own_anchor_rid: Optional[str], sidecar: Mapping[str, Any],
                         when: str) -> Tuple[Optional[Dict[str, Any]], Optional[Dict[str, Any]], Optional[str]]:
        """The contrast the sidecar's paired block intends for the steered run ``rid`` at (`petri_score`, -1), decided by the pass's anchor
        currency. Returns ``(contrast, park, refusal)``: the ``run_contrast`` payload to file (None when the comparison parks), the
        block for the metric row's ``extra.delta_block`` (None lifts a park by name when the contrast is filed) and the ``row_refusals`` line.

        * ``own_current`` (the composed audited `none` is a current unsteered run of the exact key with one usable reading under the judge):
          the sidecar's block files as today, ``anchor_judgment_id`` from the frame, plus ``extra.anchor_selection``;
        * ``sibling_same_source`` / ``borrowed_reference`` (the own `none` retired, never folded -- a refused row the sidecar still names --
          or not declared): the REGISTRY's per-behavior paired difference over both runs' item rows (e4 asked of the candidate: current item
          rows, none conflicted; :func:`declared_common.paired_items_from_frame`), ``computed_by registry``, under its own computation row
          named by ``extra.statistic_computation_id`` (the contrast's ``computation_id`` stays the reading's: the identity the paper frame joins
          on), the sidecar's block parked on the metric row; a statistic that cannot be formed (a side with no item rows, a behavior with no
          shared scenario) parks by name;
        * ``no_current_anchor``: parks with the currency's reason; the previous key is withdrawn by the head.

        Raises :class:`anchor_current.AnchorCurrencyUnavailable` when the pass has no frame: the GROUP refuses (the runner's rule)."""
        frame = ctx.anchor_currency()
        anchor_key = AC.AnchorKey(model_id=str(run["model_id"]), eval_id=eval_id, instrument_id=str(inst_row["instrument_id"]),
                                  token_cap_tokens=LC.int_or_none(run.get("token_cap_tokens")), trial_index=LC.int_or_none(run.get("trial_index")),
                                  pass_label=run.get("pass_label"), decode_policy_id=run.get("decode_policy_id"), lane_source_legacy=NAME,
                                  standup={"view_legacy": standup, "lane_source_legacy": NAME},
                                  own_anchor_run_id=own_anchor_rid, own_anchor_kind=(OWN_ANCHOR_KIND if own_anchor_rid else None))
        choice = frame.choose(anchor_key, METRIC, THRESHOLD, judge_id, computation_id="", steered_run_id=rid, steered_judgment_id=jid)
        if choice.state in ("sibling_same_source", "borrowed_reference"):
            # a re-picked mean: the registry's statistic is paired over ITEMS, so the anchor must carry current item rows at the metric (e4) and the
            # steered side's item state is part of the decision -- a second comparison, decided with e4 asked (the own anchor is not current
            # here, so no own-current pairing is tightened by it)
            choice = frame.choose(anchor_key, METRIC, THRESHOLD, judge_id, computation_id="", needs_items=True, steered_run_id=rid, steered_judgment_id=jid)
        self._anchor_states[choice.state] = self._anchor_states.get(choice.state, 0) + 1
        selection = choice.selection_json()
        own_text = (f"{own_anchor_rid} ({OWN_ANCHOR_KIND})" if own_anchor_rid
                    else "none declared (neither the sidecar's anchor block nor the audit names an unsteered run of this standup)")
        key_text = (f"key (cap {anchor_key.token_cap_tokens}, trial {anchor_key.trial_index}, pass {anchor_key.pass_label}, "
                    f"instrument {anchor_key.instrument_id})")
        producer_fields = {k: sidecar.get(k) for k in ("delta", "delta_lo", "delta_hi", "delta_p", "effect_size", "delta_method", "effect_kind", "n_pairs")}

        def park_block(why: str, filed_against: Optional[str]) -> Dict[str, Any]:
            return dict(producer_fields, computed_by="producer", why_not_a_contrast_row=why,
                        anchor={"own_anchor_run_id": own_anchor_rid, "own_anchor_kind": (OWN_ANCHOR_KIND if own_anchor_rid else None),
                                "own_anchor_judgment_id": None, "state": choice.state, "own_reason": choice.own_reason, "anchor_run_id": choice.run_id,
                                "anchor_kind": choice.anchor_kind, "registry_contrast_filed_against": filed_against},
                        anchor_selection=selection, producer_contrast_extra=dict(sidecar.get("extra") or {}), producer_block=PRODUCER_BLOCK_NOTE, rule=AC.RULE)

        if choice.state == "no_current_anchor":
            self._contrasts_parked += 1
            return None, park_block(choice.why, None), (f"contrast has no current anchor at {key_text} [own anchor {own_text}: {choice.own_reason}]; "
                                                        f"filed without a contrast: {choice.why}")
        assert choice.run_id is not None and choice.measurement is not None
        if choice.state == "own_current":
            payload = {"run_id": rid, "anchor_run_id": choice.run_id, "judgment_id": jid, "metric_id": METRIC, "threshold": THRESHOLD, "computation_id": "",
                       "anchor_judgment_id": choice.anchor_judgment_id, "anchor_kind": choice.anchor_kind, **producer_fields, "computed_by": "producer",
                       "computed_utc": when, "extra": {**dict(sidecar.get("extra") or {}), "anchor_selection": selection}}
            return payload, None, None
        # a RE-PICKED anchor: the sidecar's paired block cannot follow it; the registry pairs the two runs' item rows per behavior
        retired = f"own anchor {own_text}: {choice.own_reason}" + (f" ({choice.own_why})" if choice.own_why else "")
        chosen = f"{choice.run_id} ({choice.anchor_kind}" + (", another source" if choice.cross_source else "") + ")"
        m = choice.measurement
        try:
            stat = DC.paired_items_from_frame(frame, METRIC, rid, jid, choice)
        except DC.ContrastRefusal as exc:
            self._contrasts_parked += 1
            return (None, park_block(f"producer delta against {retired}; the registry's statistic against the re-picked {chosen} is not derived: {exc.why}", None),
                    f"contrast's {retired}; no registry-derived statistic against the re-picked {chosen}: {exc.why}; filed without a contrast")
        comp = DC.reanchor_computation("paired_items", str(ctx.producer.get("code_sha") or "unverified"))
        self._reanchor_comps.setdefault(str(comp["computation_id"]), comp)
        cand = next((c for c in choice.candidates if c.run_id == choice.run_id), None)
        self._contrasts_reanchored += 1
        payload = {"run_id": rid, "anchor_run_id": choice.run_id, "judgment_id": jid, "metric_id": METRIC, "threshold": THRESHOLD, "computation_id": "",
                   "anchor_judgment_id": choice.anchor_judgment_id, "anchor_kind": choice.anchor_kind,
                   "delta": stat["delta"], "delta_lo": stat["delta_lo"], "delta_hi": stat["delta_hi"], "delta_p": stat["delta_p"],
                   "delta_method": stat["delta_method"], "effect_size": stat["effect_size"], "effect_kind": stat["effect_kind"], "n_pairs": stat["n_pairs"],
                   "computed_by": "registry", "computed_utc": when,
                   "extra": {**dict(stat["extra"]), "anchor_selection": selection, "cross_source": bool(choice.cross_source),
                             "statistic_computation_id": comp["computation_id"],
                             "contrast_caps": {"steered": anchor_key.token_cap_tokens, "anchor": anchor_key.token_cap_tokens},
                             "anchor_standup": ({"lane_source_legacy": cand.lane_source_legacy, "view_legacy": cand.view_legacy, "cluster_job_id": cand.cluster_job_id}
                                                if cand is not None else None),
                             "anchor_reading": m.reading_json(), "producer_delta_parked_on_metric": True}}
        return payload, park_block(f"producer delta against {retired}; the registry-derived contrast against {chosen} stands", choice.run_id), None

    def _anchor_run(self, view, run_key_of, stats, agg, anchors, tag, inputs, eval_id, inst_row) -> Optional[str]:
        """The standup's audited `none` run as this reader COMPOSES it -- the OWN anchor the currency decides on: the sidecar's `anchor.petri_run_key`
        when it names one, else the standup's none entry; None when neither names one (`none_declared`: the exact-key search still runs). An id
        the registry never folded (a `none` row this read refused) reads `not_in_frame` there, a reason not to use the id, never a block."""
        anchor_key = None
        for (uri, v), blk in anchors.items():
            if v == view and blk.get("petri_run_key"):
                anchor_key = blk["petri_run_key"]
                break
        if anchor_key is None:
            anchor_key = run_key_of.get((view, "none")) or ((agg.get((view, "none")) or {}).get("run_key")) or ((stats.get((view, "none")) or {}).get("petri_run_key"))
        if not anchor_key:
            return None
        return I.run_id(LC.CAMPAIGN, str(anchor_key), LC.petri_object_key(view, "none"), eval_id, str(inst_row["instrument_id"]))


